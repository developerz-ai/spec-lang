//! The todo program, end to end through the IR: the plan, the emitted
//! project, its provenance, and that every TypeScript file parses back.

#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use emit_ts::sem::app::App;
use emit_ts::sem::prov;
use std::path::Path;
use swc_common::sync::Lrc;
use swc_common::{FileName, SourceMap};
use swc_ecma_parser::{Parser, StringInput, Syntax, TsSyntax};

fn todo() -> spec_lang_ir::Program {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../pocs/todo-app/src");
    match spec_lang_ir::load_project(&dir) {
        Ok(p) => p,
        Err(e) => panic!("{}", e.render()),
    }
}

fn bun_app(p: &spec_lang_ir::Program) -> &spec_lang_ir::AppDecl {
    p.apps.iter().find(|a| a.target.as_deref() == Some("bun")).unwrap()
}

fn emitted(p: &spec_lang_ir::Program) -> Vec<prov::Tracked> {
    match emit_ts::emit_tracked(p, bun_app(p)) {
        Ok(files) => files,
        Err(d) => panic!("{}", d.human(&p.sources)),
    }
}

fn text_of<'a>(files: &'a [prov::Tracked], path: &str) -> &'a str {
    &files.iter().find(|f| f.path == path).unwrap_or_else(|| panic!("no {path}")).text
}

#[test]
fn the_plan_of_the_todo_app() {
    let p = todo();
    let app = match App::build(&p, bun_app(&p)) {
        Ok(app) => app,
        Err(d) => panic!("{}", d.human(&p.sources)),
    };
    assert_eq!(app.refusals, ["NoTask", "AlreadyDone", "NotDone"]);
    assert_eq!(app.store_env, "TODO_STORE");
    let help = "usage: todo <command> [args]\n\ncommands:\n  add <title> [--priority low|normal|high] [--tags <tag>]...\n  list [--all] [--tag <tag>]\n  done <no>\n  reopen <no>\n  rename <no> <title>\n  remove <no>\n  clear\n  stats\n";
    assert_eq!(app.help, help);
    // A law of every state is also a check on a store that is read.
    let state_laws: Vec<&str> =
        app.laws.iter().filter(|l| l.invariant.is_some()).map(|l| p.law(l.id).info.name.as_str()).collect();
    assert!(state_laws.contains(&"numbers_below_next"), "{state_laws:?}");
    let access: Vec<_> = app.rules.iter().map(|r| (r.name.as_str(), r.writes.is_empty())).collect();
    assert_eq!(
        access.iter().filter(|(_, read_only)| *read_only).map(|(n, _)| *n).collect::<Vec<_>>(),
        ["list", "stats"]
    );
}

#[test]
fn the_same_input_gives_the_same_bytes() {
    let p = todo();
    let a = emit_ts::emit(&p, bun_app(&p)).unwrap();
    let b = emit_ts::emit(&todo(), bun_app(&p)).unwrap();
    assert_eq!(a, b);
    assert!(a.windows(2).all(|w| w[0].path < w[1].path), "files are sorted by path");
}

#[test]
fn every_typescript_file_parses_back() {
    let p = todo();
    let files = emitted(&p);
    let mut seen = 0;
    for f in files.iter().filter(|f| f.path.ends_with(".ts")) {
        let cm: Lrc<SourceMap> = Default::default();
        let source = cm.new_source_file(Lrc::new(FileName::Custom(f.path.clone())), f.text.clone());
        let mut parser = Parser::new(Syntax::Typescript(TsSyntax::default()), StringInput::from(&*source), None);
        if let Err(e) = parser.parse_module() {
            panic!("{}: {:?}\n{}", f.path, e, f.text);
        }
        let errors = parser.take_errors();
        assert!(errors.is_empty(), "{}: {:?}", f.path, errors);
        seen += 1;
    }
    assert!(seen > 40, "{seen} TypeScript files");
}

#[test]
fn every_generated_file_names_its_source_and_every_line_has_provenance() {
    let p = todo();
    let files = emitted(&p);
    for f in &files {
        let rows = prov::spans(f).unwrap_or_else(|e| panic!("{e}"));
        let lines = f.text.lines().count();
        // The spans tile the file: no line of any file, runtime or generated, is outside one.
        let mut next = 1;
        for r in &rows {
            assert_eq!(r.start, next, "{}: a gap before line {}", f.path, r.start);
            assert!(r.end >= r.start, "{}: an empty span", f.path);
            next = r.end + 1;
        }
        assert_eq!(next, lines + 1, "{}: lines after the last span", f.path);
        let shim = rows[0].entry.role.starts_with("runtime shim");
        if shim {
            assert!(f.text.contains("Runtime shim of the bun backend of spec-lang build"), "{}", f.path);
            continue;
        }
        for r in &rows {
            assert!(
                !r.entry.decl.is_empty() && !r.entry.strategy.is_empty() && !r.entry.fact.is_empty(),
                "{}:{}",
                f.path,
                r.start
            );
            assert!(r.entry.slg.contains(".slg:"), "{}:{}: {}", f.path, r.start, r.entry.slg);
            assert!(!r.entry.slg.starts_with('/'), "a local path leaked: {}", r.entry.slg);
        }
        if f.path.ends_with(".ts") || f.path.starts_with("bin/") {
            assert!(f.text.contains("Generated by spec-lang build from "), "{}", f.path);
        }
    }
    let json = prov::json("bun", "apps.bun.TodoBun", &files).unwrap();
    let guard = json.lines().find(|l| l.contains(r#""decl":"todo.board.done""#) && l.contains(r#""role":"guard[1]""#));
    let guard = guard.unwrap_or_else(|| panic!("no span for guard[1] of done in\n{json}"));
    assert!(
        guard.contains(r#""file":"src/todo/board/done.ts""#) && guard.contains(r#""slg":"todo/board.slg:"#),
        "{guard}"
    );
    assert!(guard.contains("guard.early-return") && guard.contains("guards run first"), "{guard}");
}

#[test]
fn a_rule_is_guards_then_a_draft_then_the_body() {
    let p = todo();
    let files = emitted(&p);
    let done = text_of(&files, "src/todo/board/done.ts");
    let at = |needle: &str| done.find(needle).unwrap_or_else(|| panic!("no `{needle}` in\n{done}"));
    let order = [
        at(" todo.board.done guard[0]"),
        at("if (!w.tasks.has(no)) return refuse(\"NoTask\");"),
        at("if (at(w.tasks, no).status !== \"Open\") return refuse(\"AlreadyDone\");"),
        at("const tasks = draft(w.tasks);"),
        at("return commit("),
    ];
    assert!(order.windows(2).all(|w| w[0] < w[1]), "{done}");
    // A rule that assigns no state drafts nothing and hands back the world it was given.
    let stats = text_of(&files, "src/todo/board/stats.ts");
    assert!(!stats.contains("draft(") && stats.contains("return commit(w, lines, undefined);"), "{stats}");
    let commands = text_of(&files, "src/app/commands.ts");
    assert!(
        commands.contains("command(\"stats\", \"read\"") && commands.contains("command(\"add\", \"write\""),
        "{commands}"
    );
}

#[test]
fn an_unsupported_form_is_a_diagnostic_with_a_place_and_a_fix() {
    let source = "use cli;\nstate n: Int = 0;\n@on(cli(\"bump\"))\n@uses(n.write)\npub rule bump() = { n = n / 2; }\n@target(bun)\n@bin(\"t\")\n@store(file(\".t.json\"))\napp T(rules: [bump]);\n";
    let p = spec_lang_ir::load_sources(vec![("m".into(), "m.slg".into(), source.into())])
        .unwrap_or_else(|e| panic!("{}", e.render()));
    let d = emit_ts::emit(&p, &p.apps[0]).unwrap_err();
    assert_eq!(d.code, "E-UNSUPPORTED");
    assert_eq!(d.decl.as_deref(), Some("m.bump"));
    assert!(d.span.is_some() && d.notes.iter().any(|n| n.starts_with("fix: ")), "{d:?}");
}

#[test]
fn a_write_the_rule_did_not_declare_is_refused() {
    let source = "use cli;\nstate n: Int = 0;\n@on(cli(\"bump\"))\n@uses(n.read)\npub rule bump() = { n = n + 1; }\n@target(bun)\n@bin(\"t\")\n@store(file(\".t.json\"))\napp T(rules: [bump]);\n";
    let Ok(p) = spec_lang_ir::load_sources(vec![("m".into(), "m.slg".into(), source.into())]) else { return };
    let d = emit_ts::emit(&p, &p.apps[0]).unwrap_err();
    assert_eq!(d.code, "E-EFFECT-UNDECLARED");
    assert!(d.expected.is_some() && d.found.is_some());
}
