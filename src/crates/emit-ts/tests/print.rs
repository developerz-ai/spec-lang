//! The printer over the two POCs: every file it prints, twice the same; an app's project carries its
//! libraries' runtimes; a library without one is refused by name. `src/bin/corpus` judges what the printed
//! code does; these tests judge what is printed.

#![allow(clippy::panic, clippy::expect_used)]

use emit_ts::TsPrinter;
use spec_lang_lir::{Lir, OutFile, Printer};
use std::path::Path;

fn lowered(project: &str) -> Lir {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..").join(project);
    let program = match spec_lang_ir::load_project(&dir) {
        Ok(p) => p,
        Err(f) => panic!("{}", f.render()),
    };
    match spec_lang_lir::lower(&program) {
        Ok(lir) => lir,
        Err(ds) => panic!("{} diagnostics lowering {project}", ds.len()),
    }
}

fn printed(result: Result<Vec<OutFile>, Vec<spec_lang_diag::Diag>>) -> Vec<OutFile> {
    result.unwrap_or_else(|ds| panic!("refused: {:?}", ds.iter().map(|d| &d.message).collect::<Vec<_>>()))
}

fn text<'a>(files: &'a [OutFile], path: &str) -> &'a str {
    let file = files.iter().find(|f| f.path == path).unwrap_or_else(|| panic!("no {path} among the printed files"));
    std::str::from_utf8(&file.bytes).unwrap_or_else(|_| panic!("{path} is not UTF-8"))
}

#[test]
fn the_checks_project_is_the_same_bytes_twice_and_runs_every_check() {
    let lir = lowered("pocs/todo-app/src");
    let first = printed(TsPrinter.tests(&lir));
    assert_eq!(first, printed(TsPrinter.tests(&lir)));
    assert!(first.iter().any(|f| f.path == "bin/test" && f.executable));
    let checks = text(&first, "test/checks.ts");
    for check in &lir.checks {
        assert!(checks.contains(&format!("name: \"{}\"", check.name)), "{} is not run", check.name);
    }
}

#[test]
fn every_file_names_what_it_comes_from() {
    let files = printed(TsPrinter.tests(&lowered("pocs/todo-app/src")));
    let board = text(&files, "src/todo/board.ts");
    assert!(board.starts_with("// Generated by spec-lang build from module todo.board (todo/board.slg)."));
    assert!(board.contains("/** rule add (todo/board.slg:21): a number is never reused"), "{board}");
    for f in files.iter().filter(|f| f.path.ends_with(".ts")) {
        assert!(f.bytes.starts_with(b"// "), "{} starts with no comment", f.path);
    }
}

#[test]
fn a_foreign_body_is_a_call_into_the_library() {
    let files = printed(TsPrinter.tests(&lowered("pocs/platformer/src")));
    let screen = text(&files, "src/hop/screen.ts");
    assert!(screen.contains("rt.foreign(drawCubeForeign, [box, color])"), "{screen}");
}

#[test]
fn an_app_carries_its_libraries_runtimes() {
    let lir = lowered("pocs/platformer/src");
    let files = printed(TsPrinter.app(&lir, "SkyhopBun"));
    for path in ["src/lib/cli/index.ts", "src/lib/game/main.ts", "src/lib/raylib/shim.c", "src/app.ts"] {
        text(&files, path);
    }
    assert!(files.iter().any(|f| f.path == "src/lib/raylib/build.sh" && f.executable));
    assert!(text(&files, "src/main.ts").contains("rt.start(app, program, [cli, game, raylib]);"));
    assert!(text(&files, "bin/build").contains("--outfile dist/skyhop"));
}

#[test]
fn a_library_without_a_runtime_is_refused_by_name() {
    let mut lir = lowered("pocs/todo-app/src");
    for app in &mut lir.apps {
        app.shape = Some("nosuch".into());
    }
    let refused = TsPrinter.app(&lir, "TodoBun").expect_err("a library with no runtime");
    assert_eq!(refused[0].code, "E-UNSUPPORTED");
    assert!(refused[0].message.contains("`nosuch`") && refused[0].message.contains("TypeScript"));
}
