//! The program-wide files: `src/machine.ts` (the world: every state, the effect handlers, save and restore)
//! and `src/program.ts` (the program as data: rules, functions, laws, foreign calls), which a library's
//! runtime and the checks read.

use crate::expr::{Fx, P_ARROW};
use crate::file::TsFile;
use crate::module::{DO_NOT_EDIT, param_info, unsupported};
use crate::names::{camel, pascal, string_literal};
use crate::plan::Plan;
use crate::types::{Out, trivial};
use spec_lang_diag::Diag;
use spec_lang_ir::RuleId;
use spec_lang_lir::manifest::{Note, NoteValue};
use spec_lang_lir::node::{Block, Expr, ExprKind, LambdaBody, PlaceRoot, StmtKind};
use spec_lang_lir::program::Body;
use spec_lang_lir::{LTy, walk};

/// The TypeScript interface of a handler: `out` gives `Out`.
pub fn handler_type(name: &str) -> String {
    format!("{}Handler", pascal(name))
}

pub fn machine_file(plan: &Plan<'_>) -> Result<(String, String), Vec<Diag>> {
    let lir = plan.lir;
    let path = "src/machine.ts";
    let header = format!("Generated by spec-lang build: the world of the program, every state and effect handler. {DO_NOT_EDIT}");
    let mut out = Out::new(plan, TsFile::new(path, header), None);
    let mut errors = Vec::new();
    let rt = out.rt();

    // Handlers: one interface each, and the set a world holds.
    for (h, prop) in lir.handlers.iter().zip(&plan.handler_prop) {
        out.file.blank();
        out.file.line(format!("/** The `{}` effects of library `{}`. */", h.name, h.library));
        let ty = handler_type(&h.name);
        if h.ops.is_empty() {
            out.file.line(format!("export type {ty} = {rt}.Handler;"));
            continue;
        }
        out.file.open(format!("export interface {ty} extends {rt}.Handler {{"));
        for (o, name) in h.ops.iter().zip(&plan.op_name[lir.handlers.iter().position(|x| x.name == h.name).unwrap_or(0)]) {
            let params: Vec<String> = o
                .params
                .iter()
                .flatten()
                .map(|p| {
                    let t = out.ts_type(&p.ty);
                    format!("{}: {t}", camel(&p.name))
                })
                .collect();
            let r = out.ts_type(&o.result);
            out.file.line(format!("{name}({}): {r};", params.join(", ")));
        }
        out.file.close("}");
        let _ = prop;
    }
    out.file.blank();
    out.file.open("export interface Handlers {");
    out.file.line(format!("readonly [name: string]: {rt}.Handler;"));
    for (h, prop) in lir.handlers.iter().zip(&plan.handler_prop) {
        out.file.line(format!("readonly {prop}: {};", handler_type(&h.name)));
    }
    out.file.close("}");

    // The world's value at one moment.
    out.file.blank();
    out.file.line("/** Every state at one moment. */");
    out.file.open("export interface WorldValue {");
    for (s, prop) in lir.states.iter().zip(&plan.state_prop) {
        let t = out.ts_type(&s.ty);
        out.file.line(format!("readonly {prop}: {t};"));
    }
    out.file.close("}");
    out.file.blank();
    out.file.open(format!("export const worldType = new {rt}.WorldType<WorldValue>(() => ["));
    for (s, prop) in lir.states.iter().zip(&plan.state_prop) {
        let d = out.d_desc(&s.check);
        out.file.line(format!(
            "{rt}.field({}, {}, {d}),",
            string_literal(&s.info.qualified),
            string_literal(prop)
        ));
    }
    out.file.close("]);");

    // The live world.
    out.file.blank();
    out.file.line("/** The world a rule changes: every state, and what each effect handler keeps. */");
    out.file.open(format!("export class World implements {rt}.Machine {{"));
    for (s, prop) in lir.states.iter().zip(&plan.state_prop) {
        let t = out.ts_type(&s.ty);
        out.file.line(format!("{prop}: {t};"));
    }
    out.file.blank();
    out.file.line("/** Every state at its initial value, each checked against its type. */");
    out.file.open("constructor(readonly fx: Handlers) {");
    for (s, prop) in lir.states.iter().zip(&plan.state_prop) {
        let v = match &s.init {
            Some(e) => {
                if plan.needs_world(e) {
                    errors.push(unsupported(&s.info, "a state whose initial value reads the world"));
                }
                let mut fx = Fx::new(&mut out, false);
                let v = fx.expr(e).text;
                errors.append(&mut fx.errors);
                v
            }
            None => empty(&mut out, &s.ty),
        };
        out.file.line(format!("this.{prop} = {v};"));
    }
    for (s, prop) in lir.states.iter().zip(&plan.state_prop) {
        if !trivial(plan, &s.check) {
            let d = out.d_desc(&s.check);
            out.file.line(format!(
                "{rt}.check({d}, this.{prop}, {});",
                string_literal(&format!("the initial value of {}", s.info.qualified))
            ));
        }
    }
    out.file.close("}");
    out.file.blank();
    out.file.open("value(): WorldValue {");
    let props: Vec<String> = plan.state_prop.iter().map(|p| format!("{p}: this.{p}")).collect();
    out.file.line(format!("return {{ {} }};", props.join(", ")));
    out.file.close("}");
    out.file.blank();
    out.file.open("save(): unknown {");
    let saves: Vec<String> = plan.handler_prop.iter().map(|p| format!("this.fx.{p}.save()")).collect();
    out.file.line(format!("return {{ world: this.value(), fx: [{}] }};", saves.join(", ")));
    out.file.close("}");
    out.file.blank();
    out.file.open("restore(saved: unknown): void {");
    out.file.line("const { world, fx } = saved as { world: WorldValue; fx: unknown[] };");
    for p in &plan.state_prop {
        out.file.line(format!("this.{p} = world.{p};"));
    }
    for (i, p) in plan.handler_prop.iter().enumerate() {
        out.file.line(format!("this.fx.{p}.restore(fx[{i}]);"));
    }
    out.file.close("}");
    out.file.close("}");

    // The states as data.
    out.file.blank();
    out.file.open(format!("export const states: readonly {rt}.StateInfo<World>[] = ["));
    for (s, prop) in lir.states.iter().zip(&plan.state_prop) {
        let d = out.d_desc(&s.check);
        let t = out.ts_type(&s.ty);
        out.file.line(format!(
            "{{ name: {}, prop: {}, type: {d}, set: (w, v) => {{ w.{prop} = v as {t}; }} }},",
            string_literal(&s.info.qualified),
            string_literal(prop)
        ));
    }
    out.file.close("];");
    if errors.is_empty() { Ok((path.to_string(), out.file.finish())) } else { Err(errors) }
}

/// The value a state without an initial value starts with.
fn empty(out: &mut Out<'_, '_>, t: &LTy) -> String {
    let rt = out.rt();
    match t {
        LTy::Map(k, v) => {
            let (kt, vt) = (out.ts_type(k), out.ts_type(v));
            let d = out.l_desc(k);
            format!("{rt}.OrdMap.empty<{kt}, {vt}>({d})")
        }
        LTy::Set(x) => {
            let d = out.l_desc(x);
            format!("{rt}.OrdSet.empty({d})")
        }
        LTy::List(_) => "[]".into(),
        _ => format!("{rt}.none"),
    }
}

/// Whether a rule changes a state, itself or through a rule it calls.
fn writes(plan: &Plan<'_>, r: RuleId, seen: &mut Vec<RuleId>) -> bool {
    if seen.contains(&r) {
        return false;
    }
    seen.push(r);
    let rule = plan.lir.rule(r);
    let mut direct = false;
    let mut calls = Vec::new();
    if let Body::Expr(e) = &rule.body {
        scan_expr(e, &mut direct, &mut calls);
    }
    for g in &rule.guards {
        scan_expr(&g.cond, &mut direct, &mut calls);
    }
    direct || calls.into_iter().any(|c| writes(plan, c, seen))
}

fn scan_expr(e: &Expr, direct: &mut bool, calls: &mut Vec<RuleId>) {
    walk::exprs(e, &mut |x| match &x.kind {
        ExprKind::CallRule { rule, .. } => calls.push(*rule),
        ExprKind::Block(b) => scan_block(b, direct),
        ExprKind::Lambda(l) => {
            if let LambdaBody::Block(b) = &l.body {
                scan_block(b, direct);
            }
        }
        _ => {}
    });
}

fn scan_block(b: &Block, direct: &mut bool) {
    for s in &b.stmts {
        match &s.kind {
            StmtKind::Assign { place, .. } | StmtKind::Mutate { place, .. } => {
                *direct |= matches!(place.root, PlaceRoot::State(_));
            }
            StmtKind::For { body, .. } | StmtKind::While { body, .. } => scan_block(body, direct),
            StmtKind::If { then, els, .. } => {
                scan_block(then, direct);
                if let Some(e) = els {
                    scan_block(e, direct);
                }
            }
            _ => {}
        }
    }
}

/// A note as a runtime value.
pub fn note(n: &Note) -> String {
    format!(
        "{{ library: {}, name: {}, args: [{}] }}",
        string_literal(&n.library),
        string_literal(&n.name),
        note_args(&n.args)
    )
}

fn note_args(args: &[spec_lang_lir::manifest::NoteArg]) -> String {
    args.iter()
        .map(|a| format!("{{ param: {}, value: {} }}", string_literal(&a.param), note_value(&a.value)))
        .collect::<Vec<_>>()
        .join(", ")
}

fn note_value(v: &NoteValue) -> String {
    match v {
        NoteValue::Int(n) => format!("{{ kind: \"int\", value: {n}n }}"),
        NoteValue::Text(t) => format!("{{ kind: \"text\", value: {} }}", string_literal(&unescape(t))),
        NoteValue::Quantity { value, unit } => {
            format!("{{ kind: \"quantity\", value: {value}n, unit: {} }}", string_literal(unit))
        }
        NoteValue::Variant { name, args } => {
            format!("{{ kind: \"variant\", name: {}, args: [{}] }}", string_literal(name), note_args(args))
        }
    }
}

/// A note's text is kept as written; the common escapes are read here.
fn unescape(t: &str) -> String {
    t.replace("\\\"", "\"").replace("\\n", "\n").replace("\\t", "\t").replace("\\\\", "\\")
}

/// `src/program.ts`: the program as data.
pub fn program_file(plan: &Plan<'_>) -> Result<(String, String), Vec<Diag>> {
    let lir = plan.lir;
    let path = "src/program.ts";
    let header = format!(
        "Generated by spec-lang build: the program as data, what a library's runtime and the checks read. {DO_NOT_EDIT}"
    );
    let mut out = Out::new(plan, TsFile::new(path, header), None);
    let rt = out.rt();
    let world = out.machine_value("World");
    let value = out.machine_type("WorldValue");
    out.machine_value("states");

    for (i, r) in lir.rules.iter().enumerate() {
        let name = format!("{}Rule", camel(&r.info.qualified.replace('.', "_")));
        let f = out.decl(r.info.module, &plan.rule_name[i]);
        let params: Vec<String> = r.params.iter().map(|p| param_info(&mut out, p)).collect();
        let args: Vec<String> = r
            .params
            .iter()
            .enumerate()
            .map(|(k, p)| {
                let t = out.ts_type(&p.ty);
                if p.default.is_some() { format!("a[{k}] as {t} | undefined") } else { format!("a[{k}] as {t}") }
            })
            .collect();
        let result = out.l_desc(&r.result);
        let triggers: Vec<String> = r.triggers.iter().map(note).collect();
        let module = lir.modules[r.info.module.index()].name.rsplit('.').next().unwrap_or("").to_string();
        let reads = !writes(plan, spec_lang_ir::RuleId(i as u32), &mut Vec::new());
        out.file.blank();
        out.file.open(format!("export const {name}: {rt}.RuleInfo<{world}> = {{"));
        out.file.line(format!("id: {},", string_literal(&r.info.qualified)));
        out.file.line(format!("name: {},", string_literal(&r.info.name)));
        out.file.line(format!("module: {},", string_literal(&module)));
        out.file.line(format!("why: {},", why(&r.info.why)));
        out.file.line(format!("params: [{}],", params.join(", ")));
        out.file.line(format!("result: {result},"));
        out.file.line(format!("triggers: [{}],", triggers.join(", ")));
        out.file.line(format!("reads: {reads},"));
        let a = if args.is_empty() { "_a" } else { "a" };
        let mut call_args = vec!["w".to_string()];
        call_args.extend(args);
        out.file.line(format!("call: (w, {a}) => {f}({}),", call_args.join(", ")));
        out.file.close("};");
    }

    for (i, f) in lir.fns.iter().enumerate() {
        let name = format!("{}Fn", camel(&f.info.qualified.replace('.', "_")));
        let callee = out.decl(f.info.module, &plan.fn_name[i]);
        let params: Vec<String> = f.params.iter().map(|p| param_info(&mut out, p)).collect();
        let mut call_args: Vec<String> = Vec::new();
        if plan.fn_world[i] {
            call_args.push("w".into());
        }
        for (k, p) in f.params.iter().enumerate() {
            let t = out.ts_type(&p.ty);
            call_args.push(if p.default.is_some() { format!("a[{k}] as {t} | undefined") } else { format!("a[{k}] as {t}") });
        }
        let result = out.l_desc(&f.result);
        out.file.blank();
        out.file.open(format!("export const {name}: {rt}.FnInfo<{world}> = {{"));
        out.file.line(format!("id: {},", string_literal(&f.info.qualified)));
        out.file.line(format!("name: {},", string_literal(&f.info.name)));
        out.file.line(format!("why: {},", why(&f.info.why)));
        out.file.line(format!("params: [{}],", params.join(", ")));
        out.file.line(format!("result: {result},"));
        let w = if plan.fn_world[i] { "w" } else { "_w" };
        let a = if f.params.is_empty() { "_a" } else { "a" };
        out.file.line(format!("call: ({w}, {a}) => {callee}({}),", call_args.join(", ")));
        out.file.close("};");
    }

    let mut laws = Vec::new();
    for (i, l) in lir.laws.iter().enumerate() {
        let name = format!("{}Law", camel(&l.info.qualified.replace('.', "_")));
        laws.push(name.clone());
        let body = out.decl(l.info.module, &plan.law_name[i]);
        let params: Vec<String> = l.params.iter().map(|p| param_info(&mut out, p)).collect();
        let rule = |r: &RuleId| format!("{}Rule", camel(&lir.rule(*r).info.qualified.replace('.', "_")));
        let traced: Vec<String> = l.traced.iter().map(rule).collect();
        let start: Vec<String> = l.start_rules.iter().map(rule).collect();
        let mut args: Vec<String> = Vec::new();
        let world_needed = plan.needs_world(&l.body);
        if world_needed {
            args.push("w".into());
        }
        for (k, p) in l.params.iter().enumerate() {
            let t = out.ts_type(&p.ty);
            args.push(format!("a[{k}] as {t}"));
        }
        out.file.blank();
        out.file.open(format!("export const {name}: {rt}.LawInfo<{world}> = {{"));
        out.file.line(format!("id: {},", string_literal(&l.info.qualified)));
        out.file.line(format!("params: [{}],", params.join(", ")));
        out.file.line(format!("trace: {},", l.trace));
        out.file.line(format!("traced: [{}],", traced.join(", ")));
        out.file.line(format!("start: [{}],", start.join(", ")));
        let w = if world_needed { "w" } else { "_w" };
        out.file.line(format!("body: ({w}, a) => {body}({}),", args.join(", ")));
        out.file.close("};");
    }

    let rules: Vec<String> =
        lir.rules.iter().map(|r| format!("{}Rule", camel(&r.info.qualified.replace('.', "_")))).collect();
    let fns: Vec<String> = lir.fns.iter().map(|f| format!("{}Fn", camel(&f.info.qualified.replace('.', "_")))).collect();
    let mut externs = Vec::new();
    for (i, f) in lir.fns.iter().enumerate() {
        if matches!(f.body, Body::Extern(_)) {
            externs.push(out.decl(f.info.module, &format!("{}Foreign", plan.fn_name[i])));
        }
    }
    for (i, r) in lir.rules.iter().enumerate() {
        if matches!(r.body, Body::Extern(_)) {
            externs.push(out.decl(r.info.module, &format!("{}Foreign", plan.rule_name[i])));
        }
    }
    let handlers: Vec<String> = plan.handler_prop.iter().map(|h| string_literal(h)).collect();
    out.file.blank();
    out.file.line("/** The program as data. */");
    out.file.open(format!("export const program: {rt}.Program<{world}, {value}> = {{"));
    out.file.line(format!("world: (handlers) => new {world}(handlers as unknown as ConstructorParameters<typeof {world}>[0]),"));
    out.file.line("states,");
    out.file.line("value: (w) => w.value(),");
    out.file.line(format!("rules: [{}],", rules.join(", ")));
    out.file.line(format!("fns: [{}],", fns.join(", ")));
    out.file.line(format!("laws: [{}],", laws.join(", ")));
    out.file.line(format!("externs: [{}],", externs.join(", ")));
    out.file.line(format!("handlers: [{}],", handlers.join(", ")));
    out.file.close("};");
    let _ = P_ARROW;
    Ok((path.to_string(), out.file.finish()))
}

fn why(w: &Option<String>) -> String {
    w.as_ref().map_or_else(|| "undefined".to_string(), |w| string_literal(w))
}
