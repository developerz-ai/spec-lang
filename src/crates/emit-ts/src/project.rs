//! The project around the printed code: the printer's runtime and the checks' runner (copied, the same in
//! every project), configuration, and the scripts.

use spec_lang_diag::{Diag, Severity};
use spec_lang_lir::OutFile;

/// The printer's runtime and the checks' runner: `(project path, text)`.
const RUNTIME: &[(&str, &str)] = &[
    ("src/runtime/collections.ts", include_str!("../runtime/src/runtime/collections.ts")),
    ("src/runtime/failure.ts", include_str!("../runtime/src/runtime/failure.ts")),
    ("src/runtime/index.ts", include_str!("../runtime/src/runtime/index.ts")),
    ("src/runtime/int.ts", include_str!("../runtime/src/runtime/int.ts")),
    ("src/runtime/program.ts", include_str!("../runtime/src/runtime/program.ts")),
    ("src/runtime/text.ts", include_str!("../runtime/src/runtime/text.ts")),
    ("src/runtime/types.ts", include_str!("../runtime/src/runtime/types.ts")),
    ("src/runtime/values.ts", include_str!("../runtime/src/runtime/values.ts")),
    ("src/runtime/world.ts", include_str!("../runtime/src/runtime/world.ts")),
    ("test/support/checks.ts", include_str!("../runtime/test/support/checks.ts")),
    ("test/support/generate.ts", include_str!("../runtime/test/support/generate.ts")),
    ("test/support/rng.ts", include_str!("../runtime/test/support/rng.ts")),
];

const BIOME: &str = include_str!("../runtime/biome.json");
const TSCONFIG: &str = include_str!("../runtime/tsconfig.json");
const GITIGNORE: &str = include_str!("../runtime/gitignore");
const LOCK: &str = include_str!("../runtime/bun.lock");
const LOCK_NAME: &str = "spec-lang-project";

pub fn text(path: impl Into<String>, text: impl Into<String>) -> OutFile {
    OutFile { path: path.into(), bytes: text.into().into_bytes(), executable: false }
}

pub fn script(path: impl Into<String>, text: impl Into<String>) -> OutFile {
    OutFile { path: path.into(), bytes: text.into().into_bytes(), executable: true }
}

/// A generated TypeScript file, laid out as the project's own formatter lays it out.
pub fn source(path: &str, generated: &str) -> Result<OutFile, Vec<Diag>> {
    match crate::format::typescript(generated) {
        Ok(t) => Ok(text(path, t)),
        Err(why) => Err(vec![Diag::new(
            Severity::Error,
            "E-UNSUPPORTED",
            format!("TypeScript: {path} as printed does not parse ({why}): a bug of this printer"),
        )]),
    }
}

/// What every project has: runtime, runner, configuration, `bin/test`.
pub fn common(package: &str, generated_from: &str) -> Vec<OutFile> {
    let mut files: Vec<OutFile> = RUNTIME.iter().map(|(p, t)| text(*p, *t)).collect();
    files.push(text("biome.json", BIOME));
    files.push(text("tsconfig.json", TSCONFIG));
    files.push(text(".gitignore", GITIGNORE));
    files.push(text(
        "package.json",
        format!(
            "{{\n  \"name\": \"{package}\",\n  \"private\": true,\n  \"type\": \"module\",\n  \"devDependencies\": {{\n    \"@biomejs/biome\": \"2.3.8\",\n    \"@types/bun\": \"1.3.3\",\n    \"typescript\": \"5.9.3\"\n  }}\n}}\n"
        ),
    ));
    files.push(text("bun.lock", LOCK.replacen(LOCK_NAME, package, 1)));
    files.push(script(
        "bin/test",
        format!(
            "#!/usr/bin/env bash\n# Generated by spec-lang build from {generated_from}. Do not edit: change the spec and build again.\n# Runs every check of the program; one JSON line per check: {{\"check\", \"status\"}}.\nset -euo pipefail\ncd \"$(dirname \"$0\")/..\"\nexec bun test/run.ts\n"
        ),
    ));
    files.push(text(
        "test/run.ts",
        "// Generated by spec-lang build: runs every check, one JSON line each. Do not edit: change the spec and build again.\n\nimport { checks, suite } from \"./checks.ts\";\nimport { report } from \"./support/checks.ts\";\n\nreport(suite, checks);\n",
    ));
    files.push(text(
        "test/checks.test.ts",
        "// Generated by spec-lang build: every check of the program as a `bun test` test. Do not edit: change the spec and build again.\n\nimport { expect, test } from \"bun:test\";\nimport { checks, suite } from \"./checks.ts\";\nimport { Runner } from \"./support/checks.ts\";\n\nconst runner = new Runner(suite);\n\nfor (const c of checks) {\n  // A check that reaches a foreign body is blocked here: only the app runs it.\n  test(c.name, () => {\n    expect(c.run(runner)).not.toBe(\"fail\");\n  }, 60_000);\n}\n",
    ));
    files
}
