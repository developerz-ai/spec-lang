//! The program's checks as a test suite: each `test` a function in `test/<module>.ts`, the handlers' pretends
//! in `test/pretend.ts`, and `test/checks.ts`, every check in the order and with the names `spec-lang test` uses.

use crate::expr::{Fx, P_ARROW};
use crate::file::TsFile;
use crate::machine::handler_type;
use crate::module::{DO_NOT_EDIT, doc, param_info};
use crate::names::{camel, pascal, string_literal};
use crate::plan::Plan;
use crate::types::Out;
use spec_lang_diag::Diag;
use spec_lang_ir::{ModuleId, TestId};
use spec_lang_lir::node::Expected;
use spec_lang_lir::program::{CaseTarget, CheckWhat, Given};

/// The file of module `m`'s tests, if it has any.
pub fn test_file(plan: &Plan<'_>, m: ModuleId) -> Result<Option<(String, String)>, Vec<Diag>> {
    let lir = plan.lir;
    if !lir.tests.iter().any(|t| t.info.module == m) {
        return Ok(None);
    }
    let path = test_path(plan, m);
    let module = &lir.modules[m.index()];
    let header = format!(
        "Generated by spec-lang build from the tests of module {} ({}). {DO_NOT_EDIT}",
        module.name,
        plan.module_slg[m.index()]
    );
    let mut out = Out::new(plan, TsFile::new(&path, header), None);
    let mut errors = Vec::new();
    for (i, t) in lir.tests.iter().enumerate() {
        if t.info.module != m {
            continue;
        }
        doc(&mut out, "test", &t.info);
        let name = plan.test_name[i].clone();
        let w = out.machine_type("World");
        let mut fx = Fx::new(&mut out, true);
        crate::plan::assigned_in_block(&t.body, &mut fx.assigned);
        let mut list = Vec::new();
        for p in &t.params {
            let ts = fx.bind(&p.name);
            let ty = fx.out.ts_type(&p.ty);
            list.push(format!("{ts}: {ty}"));
        }
        fx.tail_block(&t.body);
        list.insert(0, format!("{}: {w}", if fx.world_used { "w" } else { "_w" }));
        let lines = fx.take_lines();
        errors.append(&mut fx.errors);
        let result = out.ts_type(&t.body.ty);
        out.file.open(format!("export function {name}({}): {result} {{", list.join(", ")));
        for l in lines {
            out.file.line(l);
        }
        out.file.close("}");
    }
    errors.append(&mut out.errors);
    if errors.is_empty() { Ok(Some((path, out.file.finish()))) } else { Err(errors) }
}

fn test_path(plan: &Plan<'_>, m: ModuleId) -> String {
    plan.module_file[m.index()].replacen("src/", "test/", 1)
}

/// `w`, or `_w` where what was printed does not read the world.
fn world_param(fx: &Fx<'_, '_, '_>) -> &'static str {
    if fx.world_used { "w" } else { "_w" }
}

/// The test function of `t`, from the checks file.
fn test_fn(out: &mut Out<'_, '_>, t: TestId) -> String {
    let plan = out.plan;
    let m = plan.lir.test(t).info.module;
    let alias = format!("{}Tests", plan.module_alias[m.index()]);
    out.file.namespace(&test_path(plan, m), &alias);
    format!("{alias}.{}", plan.test_name[t.index()])
}

/// `test/pretend.ts`: what tests run for each handler, its state kept with the world.
pub fn pretend_file(plan: &Plan<'_>) -> Result<(String, String), Vec<Diag>> {
    let lir = plan.lir;
    let path = "test/pretend.ts";
    let header = format!(
        "Generated by spec-lang build: the effect handlers the checks run, from each library's pretend.slg. {DO_NOT_EDIT}"
    );
    let mut out = Out::new(plan, TsFile::new(path, header), None);
    let mut errors = Vec::new();
    let mut made = Vec::new();
    for (hi, h) in lir.handlers.iter().enumerate() {
        let class = format!("{}Pretend", pascal(&h.name));
        let iface = handler_type(&h.name);
        out.file.type_only("src/machine.ts", &iface);
        made.push(format!("{}: new {class}()", plan.handler_prop[hi]));
        out.file.blank();
        out.file.line(format!("/** `{}` of library `{}` in the checks. */", h.name, h.library));
        out.file.open(format!("class {class} implements {iface} {{"));
        let state: Vec<(String, String, String)> = match &h.pretend {
            None => Vec::new(),
            Some(p) => p
                .state
                .iter()
                .map(|s| {
                    let t = out.ts_type(&s.ty);
                    let mut fx = Fx::new(&mut out, false);
                    let v = s.default.as_ref().map_or_else(|| "undefined".into(), |d| fx.expr(d).text);
                    errors.append(&mut fx.errors);
                    (camel(&s.name), t, v)
                })
                .collect(),
        };
        for (n, t, v) in &state {
            out.file.line(format!("#{n}: {t} = {v};"));
        }
        for (oi, o) in h.ops.iter().enumerate() {
            let name = plan.op_name[hi][oi].clone();
            let r = out.ts_type(&o.result);
            let arm = h.pretend.as_ref().and_then(|p| p.arms.get(oi)).and_then(Option::as_ref);
            let mut fx = Fx::new(&mut out, false);
            let mut params = Vec::new();
            let names: Vec<String> = match arm {
                Some(a) => a.params.iter().map(|(n, _)| n.clone()).collect(),
                None => o.params.iter().flatten().map(|p| p.name.clone()).collect(),
            };
            let tys: Vec<String> = o.params.iter().flatten().map(|p| fx.out.ts_type(&p.ty)).collect();
            for (k, (n, t)) in names.iter().zip(&tys).enumerate() {
                let ts = if arm.is_some() { fx.bind(n) } else { format!("_a{k}") };
                params.push(format!("{ts}: {t}"));
            }
            match (arm, &h.pretend) {
                (Some(a), Some(p)) => {
                    crate::plan::assigned_in(&a.body, &mut fx.assigned);
                    let mut locals = Vec::new();
                    for s in &p.state {
                        let changed = fx.assigned.contains(&s.name);
                        let ts = fx.bind(&s.name);
                        if changed {
                            fx.mark_mutable(&ts);
                        }
                        locals.push((ts, changed));
                    }
                    for ((ts, changed), (n, _, _)) in locals.iter().zip(&state) {
                        let kw = if *changed { "let" } else { "const" };
                        fx.line(format!("{kw} {ts} = this.#{n};"));
                    }
                    let v = fx.expr(&a.body).text;
                    if locals.iter().any(|(_, c)| *c) {
                        let reply = fx.bind("reply");
                        fx.line(format!("const {reply} = {v};"));
                        for ((ts, changed), (n, _, _)) in locals.iter().zip(&state) {
                            if *changed {
                                fx.line(format!("this.#{n} = {ts};"));
                            }
                        }
                        fx.line(format!("return {reply};"));
                    } else {
                        fx.line(format!("return {v};"));
                    }
                }
                _ => {
                    let rt = fx.out.rt();
                    fx.line(format!(
                        "return {rt}.stop(\"E-UNSUPPORTED\", {});",
                        string_literal(&format!("`{}.{}` has no pretend in library `{}`", h.name, o.name, h.library))
                    ));
                }
            }
            let lines = fx.take_lines();
            errors.append(&mut fx.errors);
            out.file.blank();
            out.file.open(format!("{name}({}): {r} {{", params.join(", ")));
            for l in lines {
                out.file.line(l);
            }
            out.file.close("}");
        }
        let fields: Vec<String> = state.iter().map(|(n, _, _)| format!("this.#{n}")).collect();
        out.file.blank();
        out.file.open("save(): unknown {");
        out.file.line(format!("return [{}];", fields.join(", ")));
        out.file.close("}");
        out.file.blank();
        if state.is_empty() {
            out.file.line("restore(): void {}");
        } else {
            let types: Vec<String> = state.iter().map(|(_, t, _)| t.clone()).collect();
            out.file.open("restore(saved: unknown): void {");
            out.file.line(format!("[{}] = saved as [{}];", fields.join(", "), types.join(", ")));
            out.file.close("}");
        }
        out.file.close("}");
    }
    let handlers = out.machine_type("Handlers");
    out.file.blank();
    out.file.line("/** Fresh handlers: each test starts with none of their state. */");
    out.file.open(format!("export function pretend(): {handlers} {{"));
    out.file.line(format!("return {{ {} }};", made.join(", ")));
    out.file.close("}");
    errors.append(&mut out.errors);
    if errors.is_empty() { Ok((path.to_string(), out.file.finish())) } else { Err(errors) }
}

/// `test/checks.ts`: the program as the runner reads it, and every check.
pub fn checks_file(plan: &Plan<'_>) -> Result<(String, String), Vec<Diag>> {
    let lir = plan.lir;
    let path = "test/checks.ts";
    let header =
        format!("Generated by spec-lang build: every check of the program, in `spec-lang test`'s order. {DO_NOT_EDIT}");
    let mut out = Out::new(plan, TsFile::new(path, header), None);
    let mut errors = Vec::new();
    out.file.namespace_type("test/support/checks.ts", "check");
    out.file.value("src/program.ts", "program");
    out.file.value("test/pretend.ts", "pretend");
    let world = out.machine_type("World");
    let value = out.machine_type("WorldValue");

    out.file.blank();
    out.file.open(format!("const tests: Readonly<Record<string, check.Test<{world}>>> = {{"));
    for (i, t) in lir.tests.iter().enumerate() {
        let f = test_fn(&mut out, TestId(i as u32));
        let params: Vec<String> = t.params.iter().map(|p| param_info(&mut out, p)).collect();
        let mut given = Vec::new();
        for g in &t.given {
            match g {
                Given::State { state, value } => {
                    let mut fx = Fx::new(&mut out, true);
                    let v = fx.expr(value).at(P_ARROW);
                    let w = world_param(&fx);
                    errors.append(&mut fx.errors);
                    out.machine_value("states");
                    given.push(format!(
                        "{{ state: states[{}] as check.State<{world}>, value: ({w}) => {v} }}",
                        state.index()
                    ));
                }
                Given::Test(p) => given.push(format!("{{ test: {} }}", string_literal(&lir.test(*p).info.qualified))),
            }
        }
        let args: Vec<String> = t
            .params
            .iter()
            .enumerate()
            .map(|(k, p)| {
                let ty = out.ts_type(&p.ty);
                format!("a[{k}] as {ty}")
            })
            .collect();
        let a = if args.is_empty() { "_a" } else { "a" };
        let mut call = vec!["w".to_string()];
        call.extend(args);
        out.file.open(format!("{}: {{", string_literal(&t.info.qualified)));
        out.file.line(format!("id: {},", string_literal(&t.info.qualified)));
        out.file.line(format!("params: [{}],", params.join(", ")));
        out.file.line(format!("given: [{}],", given.join(", ")));
        out.file.line(format!("body: (w, {a}) => {f}({}),", call.join(", ")));
        out.file.close("},");
    }
    out.file.close("};");

    out.file.blank();
    out.file.line("/** The program as the checks run it: pretend handlers, fresh for every check. */");
    out.file.open(format!("export const suite: check.Program<{world}, {value}> = {{"));
    out.file.line("fresh: () => program.world(pretend()),");
    out.file.line("states: program.states,");
    out.file.line("value: program.value,");
    out.file.line("tests,");
    out.file.line("laws: program.laws,");
    out.file.close("};");

    out.file.blank();
    out.file.open(format!("export const checks: readonly check.Check<{world}, {value}>[] = ["));
    for c in &lir.checks {
        let name = string_literal(&c.name);
        let run = match &c.what {
            CheckWhat::Case { target: CaseTarget::Fn(f), args, expect } => {
                let decl = lir.func(*f);
                let callee = out.decl(decl.info.module, &plan.fn_name[f.index()]);
                let mut fx = Fx::new(&mut out, true);
                let mut items: Vec<String> = Vec::new();
                if plan.fn_world[f.index()] {
                    fx.world_used = true;
                    items.push("w".into());
                }
                let mut given: Vec<String> =
                    args.iter().map(|a| a.as_ref().map_or_else(|| "undefined".into(), |x| fx.expr(x).text)).collect();
                while given.last().is_some_and(|x| x == "undefined") {
                    given.pop();
                }
                items.extend(given);
                // Arguments that may fail are evaluated before the call, whose refusal is what the row compares.
                let call = if args.iter().flatten().any(crate::expr::may_fail) {
                    let n = items.len();
                    let vars: Vec<String> = (0..n).map(|i| format!("a{i}")).collect();
                    let lets: Vec<String> = items.iter().zip(&vars).map(|(x, v)| format!("const {v} = {x};")).collect();
                    format!(
                        "({}) => {{ {} return () => {callee}({}); }}",
                        world_param(&fx),
                        lets.join(" "),
                        vars.join(", ")
                    )
                } else {
                    format!("({}) => () => {callee}({})", world_param(&fx), items.join(", "))
                };
                let run = match expect {
                    Expected::Value(e) => {
                        fx.world_used = false;
                        let v = fx.expr(e).at(P_ARROW);
                        format!("r.fnCase({call}, ({}) => {v})", world_param(&fx))
                    }
                    Expected::Fail { name, .. } => format!("r.fnCaseFails({call}, {})", string_literal(name)),
                };
                errors.append(&mut fx.errors);
                run
            }
            CheckWhat::Case { target: CaseTarget::Test(t), args, .. } => {
                let mut fx = Fx::new(&mut out, true);
                let items: Vec<String> = args.iter().flatten().map(|x| fx.expr(x).text).collect();
                let w = world_param(&fx);
                errors.append(&mut fx.errors);
                let list = format!("[{}]", items.join(", "));
                format!("r.testCase({}, ({w}) => {list})", string_literal(&lir.test(*t).info.qualified))
            }
            CheckWhat::Test(t) => format!("r.test({})", string_literal(&lir.test(*t).info.qualified)),
            CheckWhat::Property(t) => format!("r.property({})", string_literal(&lir.test(*t).info.qualified)),
            CheckWhat::Law(l) => format!("r.law({})", string_literal(&lir.law(*l).info.qualified)),
        };
        out.file.line(format!("{{ name: {name}, run: (r) => {run} }},"));
    }
    out.file.close("];");
    errors.append(&mut out.errors);
    if errors.is_empty() { Ok((path.to_string(), out.file.finish())) } else { Err(errors) }
}
