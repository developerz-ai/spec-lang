//! One generated TypeScript file while it is being built: its items, the
//! imports they need, and the provenance of each span.

use super::build as b;
use super::print::{Notes, print};
use crate::sem::prov::{Entry, Tracked};
use std::collections::BTreeMap;
use swc_common::Span;
use swc_ecma_ast::ModuleItem;

#[derive(Debug)]
pub struct File {
    pub path: String,
    /// Module (a project path or a package) to the names taken from it; true while a name is only used as a type.
    imports: BTreeMap<String, BTreeMap<String, bool>>,
    defaults: BTreeMap<String, String>,
    pub notes: Notes,
    pub items: Vec<ModuleItem>,
    /// What the file was generated from, for its header.
    pub sources: Vec<String>,
    pub entries: Vec<Entry>,
}

fn is_project(path: &str) -> bool {
    path.starts_with("src/") || path.starts_with("test/")
}

/// `./x.ts` or `../a/x.ts` from one project file to another.
fn relative(from: &str, to: &str) -> String {
    let from: Vec<&str> = from.split('/').collect();
    let to: Vec<&str> = to.split('/').collect();
    let dir = &from[..from.len() - 1];
    let common = dir.iter().zip(to.iter()).take_while(|(a, b)| a == b).count();
    let ups = dir.len() - common;
    let mut out = if ups == 0 { "./".to_string() } else { "../".repeat(ups) };
    out.push_str(&to[common..].join("/"));
    out
}

impl File {
    pub fn new(path: &str) -> Self {
        File {
            path: path.to_string(),
            imports: BTreeMap::new(),
            defaults: BTreeMap::new(),
            notes: Notes::default(),
            items: Vec::new(),
            sources: Vec::new(),
            entries: Vec::new(),
        }
    }

    fn import(&mut self, from: &str, name: &str, type_only: bool) {
        if from == self.path {
            return;
        }
        let slot = self.imports.entry(from.to_string()).or_default().entry(name.to_string()).or_insert(type_only);
        *slot = *slot && type_only;
    }

    /// A value exported by `from`, as an expression.
    pub fn value(&mut self, from: &str, name: &str) -> b::E {
        self.import(from, name, false);
        b::name(name)
    }

    /// A type exported by `from`, as a reference.
    pub fn type_ref(&mut self, from: &str, name: &str, args: Vec<b::T>) -> b::T {
        self.import(from, name, true);
        b::t_ref(name, args)
    }

    /// The default export of a package.
    pub fn default(&mut self, package: &str, name: &str) -> b::E {
        self.defaults.insert(package.to_string(), name.to_string());
        b::name(name)
    }

    /// Start a span of provenance: the position to give the node that opens it.
    pub fn anchor(&mut self, entry: Entry, why: Option<&str>) -> Span {
        let mut lines = vec![entry.anchor()];
        if let Some(why) = why {
            lines.push(format!("@why {}", why.replace('\n', " ")));
        }
        self.entries.push(entry);
        self.notes.span(&lines, &[])
    }

    pub fn finish(self, header_entry: Entry) -> Result<Tracked, std::io::Error> {
        let mut items = Vec::new();
        // Packages first, then project files; the project's formatter has the last word on order.
        for (package, name) in &self.defaults {
            items.push(b::import_default(package, name));
        }
        let (packages, files): (Vec<_>, Vec<_>) = self.imports.iter().partition(|(from, _)| !is_project(from));
        for (from, names) in packages {
            items.push(b::import(from, names.iter().map(|(n, t)| (n.clone(), *t)).collect()));
        }
        for (from, names) in files {
            items.push(b::import(&relative(&self.path, from), names.iter().map(|(n, t)| (n.clone(), *t)).collect()));
        }
        items.extend(self.items);
        let header = format!(
            "Generated by spec-lang build from {}. Do not edit: change the spec and build again.",
            self.sources.join(", ")
        );
        let text = print(&header, items, &self.notes)?;
        let mut entries = vec![header_entry];
        entries.extend(self.entries);
        Ok(Tracked { path: self.path, text, entries, executable: false })
    }
}

#[cfg(test)]
mod tests {
    use super::relative;

    #[test]
    fn relative_paths() {
        assert_eq!(relative("src/todo/board/add.ts", "src/todo/model/task.ts"), "../model/task.ts");
        assert_eq!(relative("src/todo/board/add.ts", "src/todo/board/world.ts"), "./world.ts");
        assert_eq!(relative("test/todo/laws.test.ts", "src/app/world.ts"), "../../src/app/world.ts");
        assert_eq!(relative("src/main.ts", "src/app/app.ts"), "./app/app.ts");
    }
}
