//! One spec-lang module as one TypeScript file: its types (a TypeScript type and a runtime `Type` of the same
//! name), constants, functions, rules and laws, in declaration order within each kind.

use crate::expr::{Fx, P_ARROW, P_UNARY, Sink, may_fail};
use crate::file::TsFile;
use crate::names::{string_literal, template_part};
use crate::plan::Plan;
use crate::types::{Out, trivial};
use spec_lang_diag::Diag;
use spec_lang_ir::ModuleId;
use spec_lang_lir::program::{Body, Extern, Info, Param, TypeDef};
use spec_lang_lir::{DTy, LTy};

pub const DO_NOT_EDIT: &str = "Do not edit: change the spec and build again.";

/// The file of module `m`.
pub fn module_file(plan: &Plan<'_>, m: ModuleId) -> Result<(String, String), Vec<Diag>> {
    let lir = plan.lir;
    let path = plan.module_file[m.index()].clone();
    let module = &lir.modules[m.index()];
    let header = format!(
        "Generated by spec-lang build from module {} ({}). {DO_NOT_EDIT}",
        module.name,
        plan.module_slg[m.index()]
    );
    let mut out = Out::new(plan, TsFile::new(&path, header), Some(m));
    let mut errors = Vec::new();
    for (i, t) in lir.types.iter().enumerate() {
        if t.info.module == m && !t.builtin {
            type_decl(&mut out, i, &mut errors);
        }
    }
    for (i, c) in lir.consts.iter().enumerate() {
        if c.info.module == m {
            const_decl(&mut out, i, &mut errors);
        }
    }
    for (i, f) in lir.fns.iter().enumerate() {
        if f.info.module == m {
            fn_decl(&mut out, i, &mut errors);
        }
    }
    for (i, r) in lir.rules.iter().enumerate() {
        if r.info.module == m {
            rule_decl(&mut out, i, &mut errors);
        }
    }
    for (i, l) in lir.laws.iter().enumerate() {
        if l.info.module == m {
            law_decl(&mut out, i, &mut errors);
        }
    }
    if !errors.is_empty() {
        return Err(errors);
    }
    Ok((path, out.file.finish()))
}

/// `/** why */` and where the declaration is written.
pub fn doc(out: &mut Out<'_, '_>, kind: &str, info: &Info) {
    let at = out.plan.slg(info.module, info.span);
    out.file.blank();
    match &info.why {
        Some(why) => out.file.line(format!("/** {kind} {} ({at}): {} */", info.name, why.replace("*/", "* /"))),
        None => out.file.line(format!("/** {kind} {} ({at}) */", info.name)),
    }
}

fn type_decl(out: &mut Out<'_, '_>, i: usize, errors: &mut Vec<Diag>) {
    let plan = out.plan;
    let t = &plan.lir.types[i];
    let name = plan.type_name[i].clone();
    let q = string_literal(&t.info.qualified);
    let rt = out.rt();
    match &t.def {
        TypeDef::Alias { of } => {
            doc(out, "type", &t.info);
            let ts = out.d_ts_type(of);
            out.file.line(format!("export type {name} = {ts};"));
            let d = out.d_desc(of);
            out.file.line(format!("export const {name} = {rt}.alias<{ts}>({q}, () => {d});"));
        }
        TypeDef::Record { fields } => {
            doc(out, "type", &t.info);
            out.file.open(format!("export interface {name} {{"));
            for (f, prop) in fields.iter().zip(&plan.field_prop[i][0]) {
                let ft = out.ts_type(&f.ty);
                out.file.line(format!("readonly {prop}: {ft};"));
            }
            out.file.close("}");
            out.file.blank();
            out.file.open(format!("export const {name} = {rt}.record<{name}>({q}, () => ["));
            for (f, prop) in fields.iter().zip(&plan.field_prop[i][0]) {
                let line = field_desc(out, f, prop, errors);
                out.file.line(format!("{line},"));
            }
            out.file.close("]);");
        }
        TypeDef::Sum { variants } => {
            doc(out, "type", &t.info);
            let mut members = Vec::new();
            for (v, props) in variants.iter().zip(&plan.field_prop[i]) {
                let mut parts = vec![format!("readonly kind: {}", string_literal(&v.name))];
                for (f, prop) in v.fields.iter().zip(props) {
                    let ft = out.ts_type(&f.ty);
                    parts.push(format!("readonly {prop}: {ft}"));
                }
                members.push(format!("{{ {} }}", parts.join("; ")));
            }
            let one_line = format!("export type {name} = {};", members.join(" | "));
            if one_line.len() <= 120 {
                out.file.line(one_line);
            } else {
                let n = members.len();
                let mut text = format!("export type {name} =");
                for (k, m) in members.into_iter().enumerate() {
                    text.push_str(&format!("\n  | {m}{}", if k + 1 == n { ";" } else { "" }));
                }
                out.file.line(text);
            }
            out.file.open(format!("export const {name} = {rt}.oneOf<{name}>({q}, () => ["));
            for (v, props) in variants.iter().zip(&plan.field_prop[i]) {
                if v.fields.is_empty() {
                    out.file.line(format!("{rt}.variant({}),", string_literal(&v.name)));
                    continue;
                }
                let fs: Vec<String> =
                    v.fields.iter().zip(props).map(|(f, prop)| field_desc(out, f, prop, errors)).collect();
                out.file.line(format!("{rt}.variant({}, [{}]),", string_literal(&v.name), fs.join(", ")));
            }
            out.file.close("]);");
        }
        TypeDef::RuleSet { .. } => {}
    }
}

fn field_desc(out: &mut Out<'_, '_>, f: &spec_lang_lir::program::Field, prop: &str, errors: &mut Vec<Diag>) -> String {
    let rt = out.rt();
    let d = out.d_desc(&f.check);
    let base = format!("{rt}.field({}, {}, {d}", string_literal(&f.name), string_literal(prop));
    match &f.default {
        None => format!("{base})"),
        Some(e) => {
            let mut fx = Fx::new(out, false);
            let v = fx.expr(e).at(P_ARROW);
            errors.append(&mut fx.errors);
            format!("{base}, () => {v})")
        }
    }
}

fn const_decl(out: &mut Out<'_, '_>, i: usize, errors: &mut Vec<Diag>) {
    let plan = out.plan;
    let c = &plan.lir.consts[i];
    let name = plan.const_name[i].clone();
    doc(out, "const", &c.info);
    if plan.needs_world(&c.value) {
        errors.push(unsupported(&c.info, "a constant that reads the world"));
        return;
    }
    let ts = out.ts_type(&c.ty);
    let mut fx = Fx::new(out, false);
    let v = fx.expr(&c.value);
    errors.append(&mut fx.errors);
    if plan.const_lazy[i] {
        let rt = out.rt();
        out.file.line(format!("export const {name} = {rt}.lazy((): {ts} => {});", v.at(P_ARROW)));
    } else {
        out.file.line(format!("export const {name}: {ts} = {};", v.text));
    }
}

/// The parameter list: `w` when the world is needed, then each with its default.
fn params(out: &mut Out<'_, '_>, world: bool, ps: &[Param], errors: &mut Vec<Diag>) -> (Vec<String>, Vec<String>) {
    let mut fx = Fx::new(out, world);
    let mut list = Vec::new();
    if world {
        let w = fx.out.machine_type("World");
        list.push(format!("w: {w}"));
    }
    let mut names = Vec::new();
    for p in ps {
        let t = fx.out.ts_type(&p.ty);
        let default = p.default.as_ref().map(|d| fx.expr(d).at(P_ARROW));
        let ts = fx.bind(&p.name);
        names.push(ts.clone());
        list.push(match default {
            Some(d) => format!("{ts}: {t} = {d}"),
            None => format!("{ts}: {t}"),
        });
    }
    errors.append(&mut fx.errors);
    (list, names)
}

/// The prologue's checks, as statements.
fn checks(fx: &mut Fx<'_, '_, '_>, ps: &[Param], names: &[String]) {
    let rt = fx.out.rt();
    for (p, n) in ps.iter().zip(names) {
        if !trivial(fx.out.plan, &p.check) {
            let d = fx.out.d_desc(&p.check);
            fx.line(format!("{rt}.check({d}, {n}, \"argument `{}`\");", template_part(&p.name)));
        }
    }
}

/// A function's signature line: `export function name(params): R {`.
fn signature(name: &str, list: &[String], result: &str) -> String {
    let one = format!("export function {name}({}): {result} {{", list.join(", "));
    if one.len() <= 120 {
        return one;
    }
    let mut s = format!("export function {name}(\n");
    for p in list {
        s.push_str(&format!("  {p},\n"));
    }
    s.push_str(&format!("): {result} {{"));
    s
}

/// Binds the parameters in `fx` under the names `params` chose.
fn bind_params(fx: &mut Fx<'_, '_, '_>, ps: &[Param], names: &[String]) {
    for (p, n) in ps.iter().zip(names) {
        fx.bind_named(&p.name, n);
    }
}

fn result_check(fx: &mut Fx<'_, '_, '_>, check: &Option<DTy>) {
    if let Some(c) = check
        && !trivial(fx.out.plan, c)
    {
        fx.result = Some(fx.out.d_desc(c));
    }
}

fn fn_decl(out: &mut Out<'_, '_>, i: usize, errors: &mut Vec<Diag>) {
    let plan = out.plan;
    let f = &plan.lir.fns[i];
    let name = plan.fn_name[i].clone();
    let world = plan.fn_world[i];
    doc(out, "fn", &f.info);
    if let Body::Extern(x) = &f.body {
        extern_info(out, &name, &f.info, x, &f.params, &f.result);
    }
    let (list, names) = params(out, world, &f.params, errors);
    let result = out.ts_type(&f.result);
    out.file.open(signature(&name, &list, &result));
    let mut fx = Fx::new(out, world);
    if let Body::Expr(e) = &f.body {
        crate::plan::assigned_in(e, &mut fx.assigned);
    }
    bind_params(&mut fx, &f.params, &names);
    checks(&mut fx, &f.params, &names);
    result_check(&mut fx, &f.result_check);
    body(&mut fx, &f.body, &name, &names, &f.result);
    let lines = fx.take_lines();
    errors.append(&mut fx.errors);
    for l in lines {
        out.file.line(l);
    }
    out.file.close("}");
}

fn body(fx: &mut Fx<'_, '_, '_>, b: &Body, name: &str, names: &[String], result: &LTy) {
    match b {
        Body::Expr(e) => fx.tail(e, Sink::Return),
        Body::Extern(_) => {
            let rt = fx.out.rt();
            let t = fx.out.ts_type(result);
            fx.line(format!("return {rt}.foreign({name}Foreign, [{}]) as {t};", names.join(", ")));
        }
    }
}

/// What a `foreign` declaration is, beside its function: what a library's runtime binds.
fn extern_info(out: &mut Out<'_, '_>, name: &str, info: &Info, x: &Extern, ps: &[Param], result: &LTy) {
    let rt = out.rt();
    let params: Vec<String> = ps.iter().map(|p| param_info(out, p)).collect();
    let r = out.l_desc(result);
    out.file.open(format!("export const {name}Foreign: {rt}.ExternInfo = {{"));
    out.file.line(format!("id: {},", string_literal(&info.qualified)));
    out.file.line(format!("lang: {},", string_literal(&x.lang)));
    out.file.line(format!("library: {},", string_literal(&x.library)));
    out.file.line(format!("symbol: {},", string_literal(&x.symbol)));
    out.file.line(format!("params: [{}],", params.join(", ")));
    out.file.line(format!("result: {r},"));
    out.file.close("};");
    out.file.blank();
}

/// `{ name, type, hasDefault }` of a parameter.
pub fn param_info(out: &mut Out<'_, '_>, p: &Param) -> String {
    let d = out.d_desc(&p.check);
    format!("{{ name: {}, type: {d}, hasDefault: {} }}", string_literal(&p.name), p.default.is_some())
}

fn rule_decl(out: &mut Out<'_, '_>, i: usize, errors: &mut Vec<Diag>) {
    let plan = out.plan;
    let r = &plan.lir.rules[i];
    let name = plan.rule_name[i].clone();
    doc(out, "rule", &r.info);
    if let Body::Extern(x) = &r.body {
        extern_info(out, &name, &r.info, x, &r.params, &r.result);
    }
    let (list, names) = params(out, true, &r.params, errors);
    let result = out.ts_type(&r.result);
    out.file.open(signature(&name, &list, &result));
    let rt = out.rt();
    out.file.open(format!("return {rt}.atomic(w, () => {{"));
    let mut fx = Fx::new(out, true);
    if let Body::Expr(e) = &r.body {
        crate::plan::assigned_in(e, &mut fx.assigned);
    }
    bind_params(&mut fx, &r.params, &names);
    checks(&mut fx, &r.params, &names);
    for g in &r.guards {
        let error = string_literal(&g.error);
        if may_fail(&g.cond) {
            let c = fx.expr(&g.cond).at(P_ARROW);
            fx.line(format!("if (!{rt}.holds(() => {c})) {rt}.fail({error});"));
        } else {
            let c = fx.expr(&g.cond).at(P_UNARY);
            fx.line(format!("if (!{c}) {rt}.fail({error});"));
        }
    }
    result_check(&mut fx, &r.result_check);
    body(&mut fx, &r.body, &name, &names, &r.result);
    let lines = fx.take_lines();
    errors.append(&mut fx.errors);
    for l in lines {
        out.file.line(l);
    }
    out.file.close("});");
    out.file.close("}");
}

fn law_decl(out: &mut Out<'_, '_>, i: usize, errors: &mut Vec<Diag>) {
    let plan = out.plan;
    let l = &plan.lir.laws[i];
    let name = plan.law_name[i].clone();
    let world = plan.needs_world(&l.body);
    doc(out, "law", &l.info);
    let (list, names) = params(out, world, &l.params, errors);
    out.file.open(signature(&name, &list, "boolean"));
    let mut fx = Fx::new(out, world);
    crate::plan::assigned_in(&l.body, &mut fx.assigned);
    bind_params(&mut fx, &l.params, &names);
    fx.tail(&l.body, Sink::Return);
    let lines = fx.take_lines();
    errors.append(&mut fx.errors);
    for l in lines {
        out.file.line(l);
    }
    out.file.close("}");
}

pub fn unsupported(info: &Info, what: &str) -> Diag {
    Diag::error("E-UNSUPPORTED", info.span, format!("TypeScript: {what}")).with_decl(info.qualified.clone())
}
