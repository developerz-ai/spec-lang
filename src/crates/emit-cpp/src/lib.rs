//! The C++23 printer of `spec-lang build` (`docs/decisions/009-one-compiler-any-language.md`).
//!
//! [`Cpp`] prints any lowered program: one header and one source per module, `program::Machine` (the
//! world, the handlers, the atomic step), a runtime prelude, and the program's checks as an executable.
//! It knows C++ and its own runtime; a library's runtime comes from `libs/<name>/real/cpp/`.

mod app;
mod checks;
mod decls;
mod emit;
mod facts;
mod machine;
mod manifest;
mod names;
mod project;
mod source;
mod unicode;

use decls::Unit;
use emit::Gen;
use project::{file, runtime_file, script};
use source::Lines;
use spec_lang_diag::Diag;
use spec_lang_lir::{Lir, OutFile, Printer};

/// The C++ printer.
#[derive(Debug)]
pub struct Cpp;

/// The one instance `spec-lang build` lists.
pub static PRINTER: Cpp = Cpp;

/// What every project has: the program's code, the machine, the checks, the runtime.
struct Printed {
    units: Vec<Unit>,
    plain: Vec<OutFile>,
}

fn program(g: &Gen<'_>, lines: &Lines, real_foreign: bool) -> Printed {
    let lir = g.lir;
    let used = source::variant_fields(lir);
    let mut units = Vec::new();
    for m in &lir.modules {
        units.extend(decls::module(g, lines, m.id, &used));
    }
    units.extend(machine::machine(g, lines));
    units.extend(machine::foreign(g, lines, real_foreign));
    units.push(checks::checks(g, lines));
    let mut plain: Vec<OutFile> = project::RUNTIME.iter().map(|(p, t)| runtime_file(p, t)).collect();
    plain.extend(project::TEST_RUNTIME.iter().map(|(p, t)| runtime_file(p, t)));
    if source::uses_prim(lir, spec_lang_lir::Prim::TextLower) {
        plain.push(runtime_file("src/rt/lower.cpp", &unicode::lower_source(project::LOWER_TEMPLATE)));
    }
    plain.push(file(".clang-format", project::STYLE));
    plain.push(file(".gitignore", "build/\n"));
    Printed { units, plain }
}

fn finish(g: &Gen<'_>, printed: Printed, extra: impl FnOnce(&[OutFile]) -> Vec<OutFile>) -> Result<Vec<OutFile>, Vec<Diag>> {
    let errors = std::mem::take(&mut *g.errors.borrow_mut());
    if !errors.is_empty() {
        return Err(errors);
    }
    let mut files = project::formatted(printed.units)?;
    files.extend(printed.plain);
    let more = extra(&files);
    files.extend(more);
    files.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(files)
}

const TEST_SCRIPT: &str = "#!/usr/bin/env bash
# Generated by spec-lang build. Builds the program's checks and runs them: one JSON line per check,
# {\"check\": ..., \"status\": \"pass\" | \"fail\" | \"blocked\"}.
set -euo pipefail
cd \"$(dirname \"$0\")/..\"
generator=()
command -v ninja >/dev/null && generator=(-G Ninja)
cmake -S . -B build \"${generator[@]}\" -DCMAKE_BUILD_TYPE=Release >build.log 2>&1 || { cat build.log >&2; exit 1; }
cmake --build build --parallel >>build.log 2>&1 || { cat build.log >&2; exit 1; }
exec build/checks
";

impl Printer for Cpp {
    fn targets(&self) -> &'static [&'static str] {
        &["cpp"]
    }

    fn tests(&self, lir: &Lir) -> Result<Vec<OutFile>, Vec<Diag>> {
        let g = Gen::new(lir);
        let lines = Lines::read(lir);
        let printed = program(&g, &lines, false);
        finish(&g, printed, |files| {
            let cmake = format!(
                "# Generated by spec-lang build: the program's checks as one executable.\n{}\n# The checks are run once: built for a short build, not for speed.\nset(CMAKE_CXX_FLAGS_RELEASE \"-O1\")\n\nadd_executable(checks\n{}{})\ntarget_include_directories(checks PRIVATE include tests)\n",
                project::CMAKE_HEAD.replace("@NAME@", "checks"),
                project::sources(files, "src/"),
                project::sources(files, "tests/"),
            );
            vec![file("CMakeLists.txt", &cmake), script("bin/test", TEST_SCRIPT)]
        })
    }

    fn app(&self, lir: &Lir, app: &str) -> Result<Vec<OutFile>, Vec<Diag>> {
        app::app(lir, app)
    }
}
