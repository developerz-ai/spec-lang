//! One header and one source per module: its types, constants, `fn`s and rules.

use crate::emit::{Fx, Gen, Ret};
use crate::names::{ident, path, string_literal};
use crate::source::{Lines, Reach, file_of};
use spec_lang_ir::{ModuleId, TypeId};
use spec_lang_lir::node::Expr;
use spec_lang_lir::{Body, DTy, Extern, Info, LTy, Param, TypeDef};
use std::collections::BTreeSet;
use std::fmt::Write;

/// A file before formatting.
#[derive(Debug)]
pub struct Unit {
    pub path: String,
    pub text: String,
}

/// What a module declares, by id.
#[derive(Debug, Default)]
pub struct ModuleDecls {
    pub types: Vec<TypeId>,
    pub consts: Vec<usize>,
    pub fns: Vec<usize>,
    pub rules: Vec<usize>,
}

impl ModuleDecls {
    pub fn of(g: &Gen<'_>, m: ModuleId) -> ModuleDecls {
        let lir = g.lir;
        ModuleDecls {
            types: (0..lir.types.len())
                .filter(|i| lir.types[*i].info.module == m && !lir.types[*i].builtin)
                .map(|i| TypeId(i as u32))
                .collect(),
            consts: (0..lir.consts.len()).filter(|i| lir.consts[*i].info.module == m).collect(),
            fns: (0..lir.fns.len()).filter(|i| lir.fns[*i].info.module == m).collect(),
            rules: (0..lir.rules.len()).filter(|i| lir.rules[*i].info.module == m).collect(),
        }
    }

    pub fn is_empty(&self) -> bool {
        self.types.is_empty() && self.consts.is_empty() && self.fns.is_empty() && self.rules.is_empty()
    }
}

/// The comment above a declaration: its `@why`, then what it is and where it was written.
pub fn origin(g: &Gen<'_>, lines: &Lines, kind: &str, info: &Info) -> String {
    let mut out = String::new();
    if let Some(why) = &info.why {
        let _ = writeln!(out, "// {}", why.replace('\n', " "));
    }
    let _ = writeln!(out, "// {kind} {} ({})", info.qualified, lines.at(g.lir, info));
    out
}

/// The first line of a generated file.
pub fn banner(what: &str) -> String {
    format!("// Generated by spec-lang build from {what}. Do not edit: change the spec.\n")
}

/// The parameter list of a `fn` or rule, without and with its C++ default arguments.
fn params(g: &Gen<'_>, fx: &mut Fx<'_, '_>, ps: &[Param], lead: Option<&str>) -> (String, String) {
    let mut plain: Vec<String> = lead.map(str::to_string).into_iter().collect();
    let mut defaulted = plain.clone();
    let from = g.first_cpp_default(ps);
    for (i, p) in ps.iter().enumerate() {
        let name = fx.declare(&p.name);
        let one = format!("{}{} {name}", fx.mark(&name), g.param_dty(&p.ty, &p.check));
        plain.push(one.clone());
        match (&p.default, i >= from) {
            (Some(d), true) => {
                let mut dfx = Fx::new(g, None, d.span);
                let value = dfx.expr_typed(d);
                defaulted.push(format!("{one} = {}", dfx.resolve(&value)));
            }
            _ => defaulted.push(one),
        }
    }
    (plain.join(", "), defaulted.join(", "))
}

fn result(g: &Gen<'_>, t: &LTy, check: &Option<DTy>) -> String {
    match (t, check) {
        (LTy::Unit, _) => "void".into(),
        (LTy::Func(..) | LTy::Step(_) | LTy::Event(_) | LTy::Reply(_) | LTy::World, _) | (_, None) => g.ty(t),
        (_, Some(d)) => g.dty(d),
    }
}

/// One declaration of a module's header.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Item {
    Type(TypeId),
    Const(usize),
    Fn(usize),
    Rule(usize),
}

/// What a declaration needs declared before it in its own header.
struct Needs<'g, 'a> {
    g: &'g Gen<'a>,
    /// Each with whether C++ needs it complete (`true`) or only declared: behind a collection or a box.
    items: Vec<(Item, bool)>,
    hard: bool,
}

impl Needs<'_, '_> {
    fn push(&mut self, item: Item) {
        self.items.push((item, self.hard));
    }
    fn dty(&mut self, d: &DTy) {
        match d {
            DTy::Named(t) => self.push(Item::Type(*t)),
            DTy::Option(t) | DTy::Where(t, _) => self.dty(t),
            DTy::List(t) | DTy::Set(t) => {
                let hard = std::mem::replace(&mut self.hard, false);
                self.dty(t);
                self.hard = hard;
            }
            DTy::Map(k, v) => {
                let hard = std::mem::replace(&mut self.hard, false);
                self.dty(k);
                self.dty(v);
                self.hard = hard;
            }
            DTy::Tuple(ts) => ts.iter().for_each(|t| self.dty(t)),
            _ => {}
        }
    }
    fn lty(&mut self, t: &LTy) {
        match t {
            LTy::Named(id) => self.push(Item::Type(*id)),
            LTy::Option(t) | LTy::List(t) | LTy::Set(t) => self.lty(t),
            LTy::Map(k, v) => {
                self.lty(k);
                self.lty(v);
            }
            LTy::Tuple(ts) => ts.iter().for_each(|t| self.lty(t)),
            LTy::Func(ps, r) => {
                ps.iter().for_each(|t| self.lty(t));
                self.lty(r);
            }
            _ => {}
        }
    }
    /// An expression printed in the header: a default, a constant's value.
    fn expr(&mut self, e: &Expr) {
        use spec_lang_lir::node::ExprKind;
        let mut found = Vec::new();
        let mut types = Vec::new();
        spec_lang_lir::walk::exprs(e, &mut |x| {
            types.push(x.ty.clone());
            match &x.kind {
                ExprKind::CallFn { func, .. } => found.push(Item::Fn(func.index())),
                ExprKind::CallRule { rule, .. } => found.push(Item::Rule(rule.index())),
                ExprKind::Const(c) => found.push(Item::Const(c.index())),
                ExprKind::Construct { ty, .. } | ExprKind::Variant { ty, .. } => found.push(Item::Type(*ty)),
                _ => {}
            }
        });
        found.into_iter().for_each(|i| self.push(i));
        types.iter().for_each(|t| self.lty(t));
    }
    fn params(&mut self, ps: &[Param]) {
        let from = self.g.first_cpp_default(ps);
        for (i, p) in ps.iter().enumerate() {
            self.dty(&p.check);
            self.lty(&p.ty);
            if let (true, Some(d)) = (i >= from, &p.default) {
                self.expr(d);
            }
        }
    }
    fn of(g: &Gen<'_>, item: Item) -> Vec<(Item, bool)> {
        let lir = g.lir;
        let mut n = Needs { g, items: Vec::new(), hard: true };
        match item {
            Item::Type(t) => {
                let fields: Vec<(Option<u32>, u32, &spec_lang_lir::Field)> = match &lir.ty(t).def {
                    TypeDef::Alias { of } => {
                        n.dty(of);
                        Vec::new()
                    }
                    TypeDef::Record { fields } => fields.iter().enumerate().map(|(i, f)| (None, i as u32, f)).collect(),
                    TypeDef::Sum { variants } => variants
                        .iter()
                        .enumerate()
                        .flat_map(|(tag, v)| {
                            v.fields.iter().enumerate().map(move |(i, f)| (Some(tag as u32), i as u32, f))
                        })
                        .collect(),
                    TypeDef::RuleSet { .. } => Vec::new(),
                };
                for (tag, i, f) in fields {
                    n.hard = !g.is_boxed(t, tag, i);
                    n.dty(&f.check);
                    n.hard = true;
                    f.default.iter().for_each(|d| n.expr(d));
                }
            }
            Item::Const(i) => {
                let d = &lir.consts[i];
                n.lty(&d.ty);
                d.declared.iter().for_each(|t| n.dty(t));
                if g.const_is_plain(spec_lang_ir::ConstId(i as u32)) {
                    n.expr(&d.value);
                }
            }
            Item::Fn(i) => {
                let d = &lir.fns[i];
                n.params(&d.params);
                n.lty(&d.result);
                d.result_check.iter().for_each(|t| n.dty(t));
            }
            Item::Rule(i) => {
                let d = &lir.rules[i];
                n.params(&d.params);
                n.lty(&d.result);
                d.result_check.iter().for_each(|t| n.dty(t));
            }
        }
        n.items
    }
}

/// A module's declarations in an order C++ accepts: each after what its header text names.
fn header_order(g: &Gen<'_>, decls: &ModuleDecls) -> (Vec<Item>, Vec<TypeId>) {
    fn visit(
        g: &Gen<'_>,
        item: Item,
        hard: bool,
        mine: &[Item],
        done: &mut Vec<Item>,
        open: &mut Vec<Item>,
        early: &mut Vec<TypeId>,
    ) {
        if done.contains(&item) || !mine.contains(&item) {
            return;
        }
        if let (true, false, Item::Type(t)) = (open.contains(&item), hard, item) {
            // Named before it is defined, where C++ only needs it declared.
            if !early.contains(&t) {
                early.push(t);
            }
            return;
        }
        if open.contains(&item) {
            let span = match item {
                Item::Type(t) => g.lir.ty(t).info.span,
                Item::Const(i) => g.lir.consts[i].info.span,
                Item::Fn(i) => g.lir.fns[i].info.span,
                Item::Rule(i) => g.lir.rules[i].info.span,
            };
            g.unsupported(span, "a declaration whose C++ header needs itself declared first (a type that holds itself, or a default that calls back)");
            return;
        }
        open.push(item);
        for (need, hard) in Needs::of(g, item) {
            visit(g, need, hard, mine, done, open, early);
        }
        open.pop();
        done.push(item);
    }
    let mut mine: Vec<Item> = decls.types.iter().map(|t| Item::Type(*t)).collect();
    mine.extend(decls.consts.iter().map(|i| Item::Const(*i)));
    mine.extend(decls.fns.iter().map(|i| Item::Fn(*i)));
    mine.extend(decls.rules.iter().map(|i| Item::Rule(*i)));
    let mut done = Vec::new();
    let mut early = Vec::new();
    for item in &mine {
        visit(g, *item, true, &mine, &mut done, &mut Vec::new(), &mut early);
    }
    (done, early)
}

const ORDER: &str = "friend std::strong_ordering operator<=>(const {T}&, const {T}&) = default;\nfriend bool operator==(const {T}&, const {T}&) = default;\n";

fn field_decls(g: &Gen<'_>, t: TypeId, tag: Option<u32>, fields: &[spec_lang_lir::Field], out: &mut String) {
    for (i, f) in fields.iter().enumerate() {
        let ty = g.dty(&f.check);
        let ty = if g.is_boxed(t, tag, i as u32) { format!("rt::Box<{ty}>") } else { ty };
        let _ = write!(out, "{ty} {}", ident(&f.name));
        if let Some(d) = &f.default {
            let mut fx = Fx::new(g, None, d.span);
            let value = fx.expr_typed(d);
            let _ = write!(out, " = {}", fx.resolve(&value));
        }
        out.push_str(";\n");
    }
}

/// The fields of a sum some expression reads by name, with the type they have in every variant that has them.
fn accessors(g: &Gen<'_>, t: TypeId, used: &BTreeSet<(u32, String)>) -> Vec<(String, String)> {
    let TypeDef::Sum { variants } = &g.lir.ty(t).def else { return Vec::new() };
    let mut out: Vec<(String, String)> = Vec::new();
    for f in variants.iter().flat_map(|v| &v.fields) {
        if used.contains(&(t.0, f.name.clone())) && !out.iter().any(|(n, _)| *n == f.name) {
            out.push((f.name.clone(), g.dty(&f.check)));
        }
    }
    out
}

fn type_decl(g: &Gen<'_>, lines: &Lines, t: TypeId, used: &BTreeSet<(u32, String)>, out: &mut String) {
    let d = g.lir.ty(t);
    let name = ident(&d.info.name);
    out.push_str(&origin(g, lines, "type", &d.info));
    match &d.def {
        TypeDef::Alias { of } => {
            let _ = writeln!(out, "using {name} = {};", g.dty(of));
        }
        TypeDef::RuleSet { .. } => {
            let _ = writeln!(out, "using {name} = rt::Event;");
        }
        TypeDef::Record { fields } => {
            let _ = writeln!(out, "struct {name} {{");
            field_decls(g, t, None, fields, out);
            out.push_str(&ORDER.replace("{T}", &name));
            let _ = writeln!(out, "friend rt::Text show(const {name}& value);\n}};");
        }
        TypeDef::Sum { variants } if g.is_enum(t) => {
            let names: Vec<String> = variants.iter().map(|v| ident(&v.name)).collect();
            let _ = writeln!(out, "enum class {name} {{ {} }};\nrt::Text show({name} value);", names.join(", "));
        }
        TypeDef::Sum { variants } => {
            let _ = writeln!(out, "struct {name} {{");
            for (tag, v) in variants.iter().enumerate() {
                let vn = ident(&v.name);
                let _ = writeln!(out, "struct {vn} {{");
                field_decls(g, t, Some(tag as u32), &v.fields, out);
                out.push_str(&ORDER.replace("{T}", &vn));
                out.push_str("};\n");
            }
            let alts: Vec<String> = variants.iter().map(|v| ident(&v.name)).collect();
            let _ = writeln!(out, "std::variant<{}> alt;", alts.join(", "));
            for (field, ty) in accessors(g, t, used) {
                let _ = writeln!(
                    out,
                    "// `value.{field}`: stops E-TYPE-MISMATCH on a variant without it.\nconst {ty}& {}() const;",
                    ident(&field)
                );
            }
            out.push_str(&ORDER.replace("{T}", &name));
            let _ = writeln!(out, "friend rt::Text show(const {name}& value);\n}};");
        }
    }
    if g.facts.type_checks[t.index()] {
        let _ = writeln!(out, "// Whether a value conforms to {}: its claims and its fields'.", d.info.name);
        let _ = writeln!(out, "bool {}(const {name}& value);", bare(&g.valid_name(t)));
    }
    out.push('\n');
}

fn bare(qualified: &str) -> &str {
    qualified.rsplit("::").next().unwrap_or(qualified)
}

fn shown(fields: &[spec_lang_lir::Field], name: &str, from: &str) -> String {
    let mut s = format!("rt::Shown({})", string_literal(name));
    for f in fields {
        let _ = write!(s, ".field({}, {from}{})", string_literal(&f.name), ident(&f.name));
    }
    s + ".done()"
}

fn type_impl(g: &Gen<'_>, t: TypeId, used: &BTreeSet<(u32, String)>, out: &mut String) {
    let d = g.lir.ty(t);
    let name = ident(&d.info.name);
    let valid = bare(&g.valid_name(t)).to_string();
    let checks = g.facts.type_checks[t.index()];
    let mut fx = Fx::new(g, None, d.info.span);
    match &d.def {
        TypeDef::RuleSet { .. } => {}
        TypeDef::Alias { of } => {
            if let Some(c) = fx.conform(of, "value") {
                let _ = writeln!(out, "bool {valid}(const {name}& value) {{\nreturn {c};\n}}\n");
            }
        }
        TypeDef::Record { fields } => {
            let _ = writeln!(
                out,
                "rt::Text show(const {name}& value) {{\nreturn {};\n}}\n",
                shown(fields, &d.info.name, "value.")
            );
            if checks {
                let parts: Vec<String> = fields
                    .iter()
                    .enumerate()
                    .filter_map(|(i, f)| fx.conform(&f.check, &g.field("value", t, None, i as u32)))
                    .collect();
                let _ = writeln!(out, "bool {valid}(const {name}& value) {{\nreturn {};\n}}\n", parts.join(" && "));
            }
        }
        TypeDef::Sum { variants } if g.is_enum(t) => {
            let _ = writeln!(out, "rt::Text show({name} value) {{\nswitch (value) {{");
            for v in variants {
                let _ = writeln!(out, "case {name}::{}:\nreturn {};", ident(&v.name), string_literal(&v.name));
            }
            out.push_str("}\nreturn \"?\";\n}\n\n");
        }
        TypeDef::Sum { variants } => {
            let _ = writeln!(out, "rt::Text show(const {name}& value) {{");
            for v in variants {
                let vn = ident(&v.name);
                let _ = writeln!(
                    out,
                    "if ({}const auto* v = std::get_if<{name}::{vn}>(&value.alt)) {{\nreturn {};\n}}",
                    if v.fields.is_empty() { "[[maybe_unused]] " } else { "" },
                    shown(&v.fields, &v.name, "v->")
                );
            }
            out.push_str("return \"?\";\n}\n\n");
            for (field, ty) in accessors(g, t, used) {
                let _ = writeln!(out, "const {ty}& {name}::{}() const {{", ident(&field));
                let is_boxed = |v: &spec_lang_lir::Variant, field: &str| {
                    let tag = variants.iter().position(|x| std::ptr::eq(x, v)).unwrap_or(0) as u32;
                    v.fields.iter().position(|f| f.name == field).is_some_and(|i| g.is_boxed(t, Some(tag), i as u32))
                };
                for v in variants.iter().filter(|v| v.fields.iter().any(|f| f.name == field)) {
                    let _ = writeln!(
                        out,
                        "if (const auto* v = std::get_if<{}>(&alt)) {{\nreturn {}v->{};\n}}",
                        ident(&v.name),
                        if is_boxed(v, &field) { "*" } else { "" },
                        ident(&field)
                    );
                }
                let _ = writeln!(
                    out,
                    "rt::stop(\"E-TYPE-MISMATCH\", {});\n}}\n",
                    string_literal(&format!("this variant has no `{field}`"))
                );
            }
            if checks {
                let _ = writeln!(out, "bool {valid}(const {name}& value) {{");
                for (tag, v) in variants.iter().enumerate() {
                    let parts: Vec<String> = (0..v.fields.len())
                        .filter_map(|i| fx.conform(&v.fields[i].check, &g.field("(*v)", t, Some(tag as u32), i as u32)))
                        .collect();
                    if !parts.is_empty() {
                        let _ = writeln!(
                            out,
                            "if (const auto* v = std::get_if<{name}::{}>(&value.alt)) {{\nreturn {};\n}}",
                            ident(&v.name),
                            parts.join(" && ")
                        );
                    }
                }
                out.push_str("return true;\n}\n\n");
            }
        }
    }
}

/// The start of a `fn` or rule body: every parameter conforms to its declared type.
fn prologue(fx: &mut Fx<'_, '_>, ps: &[Param], out: &mut String) {
    for p in ps {
        let name = fx.local(&p.name);
        if let Some(c) = fx.conform(&p.check, &name) {
            let _ = writeln!(out, "rt::claim({c}, {});", string_literal(&format!("argument `{}`", p.name)));
        }
    }
}

/// The foreign function a declaration is bound to, as the generated code names it.
pub fn foreign_name(x: &Extern) -> String {
    let library = if x.library.is_empty() { &x.lang } else { &x.library };
    format!("foreign::{}::{}", ident(library), ident(&x.symbol))
}

/// The body after the prologue: its value, checked against the declared result when that has claims.
fn body(fx: &mut Fx<'_, '_>, b: &Body, ps: &[Param], res: &LTy, check: &Option<DTy>, out: &mut String) {
    let g = fx.g;
    let ret = if *res == LTy::Unit { Ret::Void } else { Ret::Value };
    let mut inner = String::new();
    match b {
        Body::Expr(e) => fx.tail(e, &mut inner, ret),
        Body::Extern(x) => {
            let args: Vec<String> = ps.iter().map(|p| fx.local(&p.name)).collect();
            let call = format!("{}({})", foreign_name(x), args.join(", "));
            let _ = writeln!(inner, "{}{call};", if ret == Ret::Value { "return " } else { "" });
        }
    }
    match check.as_ref().filter(|c| g.facts.checks(c) && ret == Ret::Value) {
        Some(c) => {
            let name = fx.fresh("result");
            let _ = writeln!(out, "const auto {name} = [&]() -> {} {{\n{inner}}}();", g.ty(res));
            if let Some(cond) = fx.conform(c, &name) {
                let _ = writeln!(out, "rt::claim({cond}, \"the result\");");
            }
            let _ = writeln!(out, "return {name};");
        }
        None => out.push_str(&inner),
    }
}

struct Printed {
    decl: String,
    def: String,
}

fn print_fn(g: &Gen<'_>, lines: &Lines, i: usize) -> Printed {
    let d = &g.lir.fns[i];
    let ctx = g.facts.fn_ctx[i];
    let lead = ctx.then_some("program::Machine& ctx");
    let name = ident(&d.info.name);
    let res = result(g, &d.result, &d.result_check);
    let mut fx = Fx::new(g, ctx.then_some("ctx"), d.info.span);
    let (plain, defaulted) = params(g, &mut fx, &d.params, lead);
    let mut out = String::new();
    prologue(&mut fx, &d.params, &mut out);
    body(&mut fx, &d.body, &d.params, &d.result, &d.result_check, &mut out);
    let head = origin(g, lines, "fn", &d.info);
    Printed {
        decl: fx.resolve(&format!("{head}{res} {name}({defaulted});\n")).replace("[[maybe_unused]] ", ""),
        def: fx.resolve(&format!("{head}{res} {name}({plain}) {{\n{out}}}\n\n")),
    }
}

fn print_rule(g: &Gen<'_>, lines: &Lines, i: usize) -> Printed {
    let d = &g.lir.rules[i];
    let name = ident(&d.info.name);
    let res = result(g, &d.result, &d.result_check);
    let mut fx = Fx::new(g, Some("ctx"), d.info.span);
    let (plain, defaulted) = params(g, &mut fx, &d.params, Some("program::Machine& ctx"));
    let mut out = String::new();
    prologue(&mut fx, &d.params, &mut out);
    for guard in &d.guards {
        let cond = fx.expr(&guard.cond);
        let error = string_literal(&guard.error);
        if g.facts.effects(&guard.cond).can_fail() {
            let _ = writeln!(out, "rt::guard([&] {{ return {}; }}, {error});", cond.s);
        } else {
            let _ = writeln!(out, "rt::guard({}, {error});", cond.s);
        }
    }
    body(&mut fx, &d.body, &d.params, &d.result, &d.result_check, &mut out);
    let lambda_ret = if d.result == LTy::Unit { String::new() } else { format!("() -> {}", g.ty(&d.result)) };
    let give = if d.result == LTy::Unit { "" } else { "return " };
    let mut head = origin(g, lines, "rule", &d.info);
    for t in &d.triggers {
        let _ = writeln!(head, "// @on({})", crate::manifest::note_text(t));
    }
    Printed {
        decl: fx.resolve(&format!("{head}{res} {name}({defaulted});\n")).replace("[[maybe_unused]] ", ""),
        // A rule is atomic: on any failure the world and the handlers go back to what they were.
        def: fx.resolve(&format!(
            "{head}{res} {name}({plain}) {{\n{give}ctx.atomic([&]{lambda_ret} {{\n{out}}});\n}}\n\n"
        )),
    }
}

/// The header and the source of one module.
pub fn module(g: &Gen<'_>, lines: &Lines, m: ModuleId, used: &BTreeSet<(u32, String)>) -> Vec<Unit> {
    let lir = g.lir;
    let decls = ModuleDecls::of(g, m);
    if decls.is_empty() {
        return Vec::new();
    }
    let module = &lir.modules[m.index()];
    let ns = g.module_ns(m);
    let mut head = Reach::default();
    let mut all = Reach::default();
    let mut h = String::new();
    let mut c = String::new();

    let (order, early) = header_order(g, &decls);
    for t in early {
        let _ = writeln!(h, "struct {};", ident(&lir.ty(t).info.name));
    }
    for item in order {
        match item {
            Item::Type(t) => {
                match &lir.ty(t).def {
                    TypeDef::Alias { of } => {
                        head.dty(lir, of);
                        claim_reach(g, of, &mut all);
                    }
                    TypeDef::Record { fields } => fields.iter().for_each(|f| {
                        head.dty(lir, &f.check);
                        f.default.iter().for_each(|d| head.expr(lir, d));
                        claim_reach(g, &f.check, &mut all);
                    }),
                    TypeDef::Sum { variants } => variants.iter().flat_map(|v| &v.fields).for_each(|f| {
                        head.dty(lir, &f.check);
                        f.default.iter().for_each(|d| head.expr(lir, d));
                        claim_reach(g, &f.check, &mut all);
                    }),
                    TypeDef::RuleSet { .. } => {}
                }
                type_decl(g, lines, t, used, &mut h);
                type_impl(g, t, used, &mut c);
            }
            Item::Const(i) => {
                let d = &lir.consts[i];
                let ty = d.declared.as_ref().map_or_else(|| g.ty(&d.ty), |t| g.dty(t));
                let name = ident(&d.info.name);
                let mut fx = Fx::new(g, None, d.info.span);
                let value = fx.expr_typed(&d.value);
                let value = fx.resolve(&value);
                h.push_str(&origin(g, lines, "const", &d.info));
                head.lty(lir, &d.ty);
                d.declared.iter().for_each(|t| head.dty(lir, t));
                if g.const_is_plain(spec_lang_ir::ConstId(i as u32)) {
                    head.expr(lir, &d.value);
                    let _ = writeln!(h, "inline const {ty} {name} = {value};\n");
                } else {
                    all.expr(lir, &d.value);
                    // Evaluated once, on first use.
                    let _ = writeln!(h, "const {ty}& {name}();\n");
                    let _ =
                        writeln!(c, "const {ty}& {name}() {{\nstatic const {ty} value = {value};\nreturn value;\n}}\n");
                }
            }
            Item::Fn(i) => {
                let d = &lir.fns[i];
                head.params(lir, &d.params);
                head.lty(lir, &d.result);
                d.result_check.iter().for_each(|x| head.dty(lir, x));
                head.machine |= g.facts.fn_ctx[i];
                d.params.iter().filter_map(|p| p.default.as_ref()).for_each(|x| head.expr(lir, x));
                d.params.iter().for_each(|p| claim_reach(g, &p.check, &mut all));
                if let Body::Expr(e) = &d.body {
                    all.expr(lir, e);
                }
                let p = print_fn(g, lines, i);
                h.push_str(&p.decl);
                h.push('\n');
                c.push_str(&p.def);
            }
            Item::Rule(i) => {
                let d = &lir.rules[i];
                head.params(lir, &d.params);
                head.lty(lir, &d.result);
                d.result_check.iter().for_each(|x| head.dty(lir, x));
                head.machine = true;
                d.params.iter().filter_map(|p| p.default.as_ref()).for_each(|x| head.expr(lir, x));
                d.params.iter().for_each(|p| claim_reach(g, &p.check, &mut all));
                d.guards.iter().for_each(|x| all.expr(lir, &x.cond));
                if let Body::Expr(e) = &d.body {
                    all.expr(lir, e);
                }
                let p = print_rule(g, lines, i);
                h.push_str(&p.decl);
                h.push('\n');
                c.push_str(&p.def);
            }
        }
    }

    let here = path(&module.name);
    let from = format!("module {} ({})", module.name, file_of(lir, m));
    let mut header = banner(&from);
    header.push_str("#pragma once\n\n#include \"rt/prelude.hpp\"\n");
    for other in head.modules.iter().filter(|o| **o != m) {
        if !ModuleDecls::of(g, *other).is_empty() {
            let _ = writeln!(header, "#include \"{}.hpp\"", path(&lir.modules[other.index()].name));
        }
    }
    if head.machine {
        header.push_str("\nnamespace program {\nstruct Machine;\nstruct World;\n}  // namespace program\n");
    }
    let _ = writeln!(header, "\nnamespace {ns} {{\n\n{h}}}  // namespace {ns}");

    let mut source = banner(&from);
    let _ = writeln!(source, "#include \"{here}.hpp\"\n\n#include \"program/machine.hpp\"");
    let uses_foreign = decls.fns.iter().any(|i| matches!(lir.fns[*i].body, Body::Extern(_)))
        || decls.rules.iter().any(|i| matches!(lir.rules[*i].body, Body::Extern(_)));
    if uses_foreign {
        source.push_str("#include \"program/foreign.hpp\"\n");
    }
    for other in all.modules.iter().filter(|o| **o != m && !head.modules.contains(o)) {
        if !ModuleDecls::of(g, *other).is_empty() {
            let _ = writeln!(source, "#include \"{}.hpp\"", path(&lir.modules[other.index()].name));
        }
    }
    let _ = writeln!(source, "\nnamespace {ns} {{\n\n{c}}}  // namespace {ns}");
    vec![
        Unit { path: format!("include/{here}.hpp"), text: header },
        Unit { path: format!("src/{here}.cpp"), text: source },
    ]
}

/// What the claims of a declared type call.
fn claim_reach(g: &Gen<'_>, d: &DTy, reach: &mut Reach) {
    match d {
        DTy::Where(b, c) => {
            reach.expr(g.lir, &g.lir.claim(*c).body);
            claim_reach(g, b, reach);
        }
        DTy::Option(t) | DTy::List(t) | DTy::Set(t) => claim_reach(g, t, reach),
        DTy::Map(k, v) => {
            claim_reach(g, k, reach);
            claim_reach(g, v, reach);
        }
        DTy::Tuple(ts) => ts.iter().for_each(|t| claim_reach(g, t, reach)),
        DTy::Named(t) => {
            reach.modules.insert(g.lir.ty(*t).info.module);
        }
        _ => {}
    }
}
