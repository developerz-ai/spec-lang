//! The printer over the two POCs: every file it prints, twice the same; an app's project carries its
//! libraries' runtimes; a library without one is refused by name. `src/bin/corpus` judges what the printed
//! code does; these tests judge what is printed. They need `clang-format`, as the printer does.

#![allow(clippy::panic, clippy::expect_used)]

use spec_lang_emit_cpp::PRINTER;
use spec_lang_lir::{Lir, OutFile, Printer};
use std::path::Path;

fn lowered(project: &str) -> Lir {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..").join(project);
    let program = match spec_lang_ir::load_project(&dir) {
        Ok(p) => p,
        Err(f) => panic!("{}", f.render()),
    };
    match spec_lang_lir::lower(&program) {
        Ok(lir) => lir,
        Err(ds) => panic!("{} diagnostics lowering {project}", ds.len()),
    }
}

fn text<'a>(files: &'a [OutFile], path: &str) -> &'a str {
    let file = files.iter().find(|f| f.path == path).unwrap_or_else(|| panic!("no {path} among the printed files"));
    std::str::from_utf8(&file.bytes).unwrap_or_else(|_| panic!("{path} is not UTF-8"))
}

fn printed(result: Result<Vec<OutFile>, Vec<spec_lang_diag::Diag>>) -> Vec<OutFile> {
    result.unwrap_or_else(|ds| panic!("the printer refused: {:?}", ds.iter().map(|d| &d.message).collect::<Vec<_>>()))
}

#[test]
fn the_checks_project_is_the_same_bytes_twice() {
    let lir = lowered("pocs/todo-app/src");
    let first = printed(PRINTER.tests(&lir));
    let second = printed(PRINTER.tests(&lir));
    assert_eq!(first, second);
    let test = first.iter().find(|f| f.path == "bin/test").expect("bin/test");
    assert!(test.executable);
    // Every check is named as `spec-lang test` names it.
    let checks = text(&first, "tests/checks.cpp");
    for check in &lir.checks {
        assert!(checks.contains(&format!("\"{}\"", check.name)), "{} is not run", check.name);
    }
}

#[test]
fn every_file_names_what_it_comes_from() {
    let lir = lowered("pocs/todo-app/src");
    let files = printed(PRINTER.tests(&lir));
    let board = text(&files, "src/todo/board.cpp");
    assert!(board.starts_with("// Generated by spec-lang build from module todo.board (todo/board.slg)."));
    assert!(board.contains("// rule todo.board.add (todo/board.slg:21)"));
    assert!(board.contains("// @on(cli(\"add\"))"));
    for file in files.iter().filter(|f| f.path.ends_with(".cpp") || f.path.ends_with(".hpp")) {
        let first = text(&files, &file.path).lines().next().unwrap_or("");
        assert!(first.starts_with("// "), "{} starts with no comment", file.path);
    }
}

#[test]
fn a_cli_app_carries_the_cli_runtime_and_its_manifest() {
    let lir = lowered("pocs/todo-app/src");
    let files = printed(PRINTER.app(&lir, "TodoCpp"));
    assert_eq!(files, printed(PRINTER.app(&lir, "TodoCpp")));
    let cmake = text(&files, "CMakeLists.txt");
    assert!(cmake.contains("include(lib/cli/runtime.cmake)"));
    assert!(cmake.contains("set(APP_NOTE_cli_bin_name \"todo\")"));
    assert!(text(&files, "src/main.cpp").contains("lib::cli::main(program::app(), argc, argv)"));
    let manifest = text(&files, "src/program/manifest.cpp");
    assert!(manifest.contains(".qualified = \"todo.board.add\""));
    // `list` and `stats` only read: they take the shared lock.
    let after_rule =
        |part: &&str| part.trim_start_matches(|c: char| c == ',' || c.is_whitespace()).starts_with(".writes = false");
    assert_eq!(manifest.split(".rule = true").skip(1).filter(after_rule).count(), 2);
    assert!(files.iter().any(|f| f.path == "lib/cli/run.cpp"));
    assert!(!files.iter().any(|f| f.path.starts_with("lib/game/") || f.path.starts_with("lib/raylib/")));
}

#[test]
fn a_game_app_binds_its_foreign_declarations_to_their_library() {
    let lir = lowered("pocs/platformer/src");
    let files = printed(PRINTER.app(&lir, "SkyhopCpp"));
    assert!(text(&files, "src/main.cpp").contains("lib::game::main(program::app(), argc, argv)"));
    let real = text(&files, "src/program/foreign_real.cpp");
    assert!(real.contains("lib::raylib::DrawCube(box, color)"));
    // The test build links no library: a check that reaches a foreign body is blocked.
    let blocked = text(&files, "src/program/foreign_blocked.cpp");
    assert!(blocked.contains("rt::foreign(\"hop.screen.draw_cube\", \"foreign c \\\"raylib#DrawCube\\\"\")"));
    for library in ["game", "cli", "raylib"] {
        assert!(files.iter().any(|f| f.path == format!("lib/{library}/runtime.cmake")), "no runtime of {library}");
    }
}

#[test]
fn an_app_that_does_not_exist_is_refused() {
    let lir = lowered("pocs/todo-app/src");
    assert!(PRINTER.app(&lir, "NoSuchApp").is_err());
}
