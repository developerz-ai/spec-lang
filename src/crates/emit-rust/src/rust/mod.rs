/// Collects files and their spans.
#[derive(Debug)]
pub struct Out {
    pub files: Vec<OutFile>,
    pub spans: Vec<Span>,
}

impl Out {
    fn add(&mut self, buf: FileBuf) {
        let (f, s) = buf.finish();
        self.files.push(f);
        self.spans.extend(s);
    }
}

/// The generated crate's package name: the app's `@bin`.
pub fn package(front: &Front<'_>) -> String {
    front.app().bin.clone().unwrap_or_else(|| layout::snake(&front.app().info.name))
}

pub fn emit(front: &Front<'_>, options: &crate::Options) -> Result<Vec<OutFile>, Vec<Diag>> {
    let layout = layout::plan(front, &options.off);
    let mut out = Out { files: Vec::new(), spans: Vec::new() };
    let mut diags = Vec::new();
    let mut keep = |r: Result<(), Diag>| {
        if let Err(d) = r {
            diags.push(d);
        }
    };
    for m in &layout.modules {
        for (file, items) in &m.files {
            keep(module_file(front, &layout, &m.name, file, items, &mut out));
        }
        keep(module_root(front, &layout, &m.name, &mut out));
    }
    keep(table_file(front, &layout, &mut out));
    keep(codec_file(front, &layout, &mut out));
    keep(project::app_files(front, &layout, &mut out));
    keep(tests::emit(front, &layout, &mut out));
    if !diags.is_empty() {
        return Err(diags);
    }
    for (path, text) in RUNTIME {
        let shim = path.trim_start_matches("src/").trim_end_matches(".rs").replace('/', ".");
        let origin = Origin::new("runtime", "", format!("runtime shim {shim}"));
        let mut buf = FileBuf::new(*path);
        let header = format!(
            "// Generated by spec-lang build: runtime shim {shim} of the rust backend (crates/emit-rust/runtime), emitted verbatim. Do not edit.\n"
        );
        buf.push(&format!("{header}\n{text}"), origin);
        out.add(buf);
    }
    // The store's failure paths, tested in the generated project: the shim with its package name.
    let origin = Origin::new("runtime", "", "runtime shim tests.store_failures (package name filled in)").strategy(
        "store.failure-hygiene",
        "a failed write leaves the old store and no temporary file; locks are released on every return",
    );
    let mut buf = FileBuf::new("tests/store_failures.rs");
    let text = include_str!("../../runtime/tests/store_failures.rs").replace("__PKG__", &package(front));
    buf.push(
        &format!("// Generated by spec-lang build: runtime shim tests.store_failures of the rust backend (crates/emit-rust/runtime), its package name filled in. Do not edit.\n\n{text}"),
        origin,
    );
    out.add(buf);
    let app = front.app().info.name.clone();
    let json = crate::provenance::to_json("rust", &app, out.spans.clone());
    out.files.push(OutFile { path: "provenance.json".into(), bytes: json.into_bytes(), executable: false });
    out.files.sort_by(|a, b| a.path.cmp(&b.path));
    Ok(out.files)
}

/// `// Generated by spec-lang build from <what> (<where>). Do not edit: change the spec.`
pub fn header(what: &str, at: &str) -> String {
    format!("Generated by spec-lang build from {what} ({at}). Do not edit: change the spec.")
}

fn path_of(layout: &Layout, module: &str, file: &str) -> String {
    if layout.is_dir(module) { format!("src/{module}/{file}.rs") } else { format!("src/{module}.rs") }
}

fn module_file(
    front: &Front<'_>,
    layout: &Layout,
    module: &str,
    file: &str,
    items: &[Item],
    out: &mut Out,
) -> Result<(), Diag> {
    let path = path_of(layout, module, file);
    let mut ctx = Ctx::new(front, layout, (module.to_string(), file.to_string()), "crate", Mode::Product);
    let consts = items::const_fns(&ctx);
    let mut printed: Vec<print::Printed> = Vec::new();
    let mut names = Vec::new();
    let mut ats = Vec::new();
    // Order: types, then fns, then rules, then the module's world, refusals, commands.
    let mut ordered: Vec<Item> = items.to_vec();
    ordered.sort_by_key(|i| match i {
        Item::World => 0,
        Item::Refusal => 1,
        Item::Type(_) => 2,
        Item::Fn(_) => 3,
        Item::Rule(_) => 4,
        Item::Command => 5,
    });
    for item in ordered {
        ctx.anchors.clear();
        let (ts, origin) = match item {
            Item::Type(id) => {
                let info = &front.prog.ty(id).info;
                names.push(format!("type {}", info.name));
                ats.push(front.at(info.span));
                ctx.decl = front.decl_path(info);
                {
                    let mut origin = Origin::new(front.decl_path(info), front.at(info.span), "type");
                    if let Some((_, licence)) = front.facts.inline_text.get(&id).filter(|_| layout.on("text.inline")) {
                        origin = origin.strategy("text.inline", licence.clone());
                    }
                    (items::ty(&mut ctx, id)?, origin)
                }
            }
            Item::Fn(id) => {
                let info = &front.prog.func(id).info;
                names.push(format!("fn {}", info.name));
                ats.push(front.at(info.span));
                let f = front.func(id).ok_or_else(|| Diag::unsupported(info.span, "an untyped fn"))?;
                let role = if consts.contains(&id) { "fn (const)" } else { "fn" };
                (
                    items::func(&mut ctx, f, consts.contains(&id))?,
                    Origin::new(front.decl_path(info), front.at(info.span), role),
                )
            }
            Item::Rule(id) => {
                let info = &front.prog.rule(id).info;
                names.push(format!("rule {}", info.name));
                ats.push(front.at(info.span));
                let index = front.rules.iter().position(|r| r.id == id).unwrap_or(0);
                let mut origin = Origin::new(front.decl_path(info), front.at(info.span), "rule");
                if layout.read_only(front, index) {
                    origin = origin.strategy(
                        "rule.read-only",
                        "the body assigns and removes no state, and @uses lists no write: &World, shared lock, no store write",
                    );
                }
                (items::rule(&mut ctx, index, &front.rules[index])?, origin)
            }
            Item::World => {
                let names_s: Vec<String> =
                    front.states.iter().map(|s| front.prog.state(s.id).info.name.clone()).collect();
                names.push(format!("state {}", names_s.join(", ")));
                let first =
                    front.states.first().map(|s| front.at(front.prog.state(s.id).info.span)).unwrap_or_default();
                ats.push(first.clone());
                let decl =
                    front.states.first().map(|s| front.decl_path(&front.prog.state(s.id).info)).unwrap_or_default();
                (items::world(&mut ctx)?, Origin::new(decl, first, "states as one world"))
            }
            Item::Refusal => {
                names.push(format!("the errors {} of the rules' guards", front.errors.join(", ")));
                let first =
                    front.rules.iter().find_map(|r| r.guards.first()).map(|g| front.at(g.span)).unwrap_or_default();
                ats.push(first.clone());
                (items::refusal(&mut ctx), Origin::new(format!("{}.guards", module_path(front)), first, "guard errors"))
            }
            Item::Command => {
                names.push("the events of every rule of the app".into());
                let at = front.at(front.app().info.span);
                ats.push(at.clone());
                (items::command(&mut ctx)?, Origin::new(front.decl_path(&front.app().info), at, "events and dispatch"))
            }
        };
        let (text, nested) = print::items(ts, &ctx.anchors)?;
        printed.push((text, origin, nested));
    }
    let what = names.join(", ");
    let at = ats.into_iter().filter(|a| !a.is_empty()).collect::<Vec<_>>().join(", ");
    let header_origin = printed.first().map(|p| p.1.clone()).unwrap_or_else(|| Origin::new("", "", "header"));
    let mut header_origin = header_origin;
    header_origin.role = "header and imports".into();
    header_origin.strategy = None;
    header_origin.licence = None;
    let mut f = RustFile::new(&path, &header(&what, &at), header_origin);
    for (text, origin, nested) in printed {
        f.item(text, origin, nested);
    }
    let uses = print::uses(&ctx.uses)?;
    out.add(f.finish(&uses));
    Ok(())
}

fn module_path(front: &Front<'_>) -> String {
    front.rules.first().map(|r| front.prog.module(front.prog.rule(r.id).info.module).name.clone()).unwrap_or_default()
}

/// `src/<module>/mod.rs`: the files and what they export.
fn module_root(front: &Front<'_>, layout: &Layout, module: &str, out: &mut Out) -> Result<(), Diag> {
    if !layout.is_dir(module) {
        return Ok(());
    }
    let Some(m) = layout.modules.iter().find(|m| m.name == module) else { return Ok(()) };
    let spec = front.prog.module(m.module);
    let mut mods = Vec::new();
    let mut reexports = Vec::new();
    for (file, items) in &m.files {
        let f = ident(file);
        mods.push(quote!(mod #f;));
        let mut names: Vec<String> = Vec::new();
        for it in items {
            match it {
                Item::Type(t) => names.push(front.prog.ty(*t).info.name.clone()),
                Item::Fn(id) => names.push(front.prog.func(*id).info.name.clone()),
                Item::Rule(id) => {
                    names.push(front.prog.rule(*id).info.name.clone());
                    let index = front.rules.iter().position(|r| r.id == *id).unwrap_or(0);
                    let ctx = Ctx::new(front, layout, (module.to_string(), file.clone()), "crate", Mode::Product);
                    if let Some((view, value)) = items::view_names(&ctx, index) {
                        names.push(view);
                        names.push(value);
                    }
                }
                Item::World => names.push("World".into()),
                Item::Refusal => names.push("Refusal".into()),
                Item::Command => {
                    names.push("Command".into());
                    names.push("apply".into());
                }
            }
        }
        names.sort_by(|a, b| {
            let up = |s: &str| s.chars().next().is_some_and(char::is_uppercase);
            (!up(a), a).cmp(&(!up(b), b))
        });
        let ids: Vec<_> = names.iter().map(|n| ident(n)).collect();
        reexports.push(if ids.len() == 1 { quote!(pub use #f::#(#ids)*;) } else { quote!(pub use #f::{#(#ids),*};) });
    }
    let ts = quote!(#(#mods)* #(#reexports)*);
    let (text, _) = print::items(ts, &[])?;
    let at = format!("{}:1:1", spec.path);
    let origin = Origin::new(spec.name.clone(), at.clone(), "module index");
    let mut f =
        RustFile::new(&format!("src/{module}/mod.rs"), &header(&format!("module {}", spec.name), &at), origin.clone());
    f.item(text, origin, Vec::new());
    out.add(f.finish(""));
    Ok(())
}

fn table_file(front: &Front<'_>, layout: &Layout, out: &mut Out) -> Result<(), Diag> {
    let mut ctx = Ctx::new(front, layout, ("cli".into(), "table".into()), "crate", Mode::Product);
    let (ts, rows) = table::table(&mut ctx)?;
    let text_ts = ts.to_string();
    for name in ["CommandSpec", "Flag", "FlagKind", "Positional", "ValueType", "required"] {
        if text_ts.contains(name) {
            ctx.uses.insert(format!("super::{name}"));
        }
    }
    if text_ts.contains("int (") {
        ctx.uses.insert("super::int".into());
    }
    let (text, _) = print::items(ts, &[])?;
    // Each command's row starts at its `CommandSpec {` line.
    let mut nested = Vec::new();
    let lines: Vec<&str> = text.lines().collect();
    let mut row = 0;
    for (i, l) in lines.iter().enumerate() {
        if l.trim() == "CommandSpec {"
            && let Some((_, o)) = rows.get(row)
        {
            nested.push((i as u32, o.clone()));
            row += 1;
        }
    }
    if let Some(end) = lines.iter().position(|l| l.trim_start().starts_with("];")) {
        nested.push((
            end as u32,
            Origin::new(front.decl_path(&front.app().info), front.at(front.app().info.span), "cli param table"),
        ));
    }
    let app = &front.app().info;
    let at = front.at(app.span);
    let origin = Origin::new(front.decl_path(app), at.clone(), "cli param table and help")
        .strategy("cli.derive", "every rule with @on(cli(name)) of the app, parameters by the cli vocabulary's table");
    let mut f = RustFile::new(
        "src/cli/table.rs",
        &header(&format!("the parameters of every @on(cli(...)) rule of app {}", app.name), &at),
        origin.clone(),
    );
    f.item(text, origin, nested);
    let uses = print::uses(&ctx.uses)?;
    out.add(f.finish(&uses));
    Ok(())
}

fn codec_file(front: &Front<'_>, layout: &Layout, out: &mut Out) -> Result<(), Diag> {
    let mut ctx = Ctx::new(front, layout, ("store".into(), "codec".into()), "crate", Mode::Product);
    let ts = codec::codec(&mut ctx)?;
    for name in ["cursor::Cursor", "writer::Writer", "Codec", "Decode", "StoreError", "Unreadable"] {
        ctx.uses.insert(format!("super::{name}"));
    }
    let (text, _) = print::items(ts, &[])?;
    let states: Vec<String> = front.states.iter().map(|s| front.prog.state(s.id).info.name.clone()).collect();
    let at = front.states.first().map(|s| front.at(front.prog.state(s.id).info.span)).unwrap_or_default();
    let decl = front.states.first().map(|s| front.decl_path(&front.prog.state(s.id).info)).unwrap_or_default();
    let mut licence = "the states' types fix the schema; @store(file(...)) on the app".to_string();
    if !front.facts.keyed.is_empty() {
        licence.push_str("; a Map keyed by a field of its values is stored as the array of its values");
    }
    if !front.facts.invariants.is_empty() {
        let laws: Vec<String> = front.facts.invariants.iter().map(|l| front.prog.law(*l).info.name.clone()).collect();
        licence.push_str(&format!("; laws over every state checked on read: {}", laws.join(", ")));
    }
    let origin = Origin::new(decl, at.clone(), "store codec").strategy("store.json.schema", licence);
    let mut f = RustFile::new(
        "src/store/codec.rs",
        &header(&format!("state {} under @store", states.join(", ")), &at),
        origin.clone(),
    );
    f.item(text, origin, Vec::new());
    let uses = print::uses(&ctx.uses)?;
    out.add(f.finish(&uses));
    Ok(())
}

/// Prints one generated file made of `ts` with a header; used by the project and tests.
pub fn simple_file(
    path: &str,
    what: &str,
    origin: Origin,
    ts: TokenStream,
    anchors: &[(String, Origin)],
    uses: &BTreeSet<String>,
    prelude: Option<&str>,
) -> Result<FileBuf, Diag> {
    let (text, nested) = print::items(ts, anchors)?;
    let mut f = RustFile::new(
        path,
        &header(what, &origin.slg),
        Origin { role: "header and imports".into(), strategy: None, licence: None, ..origin.clone() },
    );
    if let Some(p) = prelude {
        f.prelude(p);
    }
    f.item(text, origin, nested);
    let uses = print::uses(uses)?;
    Ok(f.finish(&uses))
}
