//! The proof: the todo program through the ir crate, emitted to
//! `pocs/todo-app/gen/rust`, and the properties every emission must have.
#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

mod common;

use std::collections::BTreeMap;

use spec_lang_emit_rust::OutFile;

fn emit() -> Vec<OutFile> {
    let (prog, app) = common::todo("TodoRust");
    spec_lang_emit_rust::emit(&prog, prog.app(app)).unwrap_or_else(|ds| {
        panic!(
            "{}",
            ds.iter()
                .map(|d| format!("{d} at {:?} in {:?}: {:?}", d.span.map(|s| prog.location(s)), d.decl, d.notes))
                .collect::<Vec<_>>()
                .join("\n")
        )
    })
}

fn text(f: &OutFile) -> &str {
    std::str::from_utf8(&f.bytes).expect("UTF-8")
}

#[test]
fn emits_the_todo_app() {
    let files = emit();
    spec_lang_emit_rust::write(&common::poc().join("gen/rust"), &files).unwrap();
    for wanted in [
        "Cargo.toml",
        "src/main.rs",
        "src/board/done.rs",
        "src/cli/table.rs",
        "src/store/codec.rs",
        "tests/laws.rs",
        "provenance.json",
    ] {
        assert!(files.iter().any(|f| f.path == wanted), "{wanted}");
    }
}

#[test]
fn every_rust_file_parses_back() {
    for f in emit().iter().filter(|f| f.path.ends_with(".rs")) {
        if let Err(e) = syn::parse_file(text(f)) {
            panic!("{}: {e}", f.path);
        }
    }
}

#[test]
fn same_program_same_bytes() {
    assert_eq!(emit(), emit());
}

#[test]
fn every_file_says_where_it_came_from() {
    for f in emit().iter().filter(|f| f.path != "provenance.json" && f.path != "Cargo.lock" && f.path != ".gitignore") {
        let head: String = text(f).lines().take(2).collect::<Vec<_>>().join("\n");
        assert!(head.contains("Generated by spec-lang build"), "{}: {head}", f.path);
        let shim = head.contains("runtime shim");
        assert!(shim || head.contains(".slg:"), "{} names no slg file:line: {head}", f.path);
    }
}

#[test]
fn nothing_names_a_local_directory() {
    let root = common::poc().canonicalize().unwrap();
    let home = root.to_string_lossy().split('/').take(3).collect::<Vec<_>>().join("/");
    for f in emit() {
        assert!(!text(&f).contains(&home), "{} contains {home}", f.path);
    }
}

/// Every line of every generated (non-runtime) file is inside some provenance span.
#[test]
fn provenance_covers_every_generated_line() {
    let files = emit();
    let json = files.iter().find(|f| f.path == "provenance.json").map(text).unwrap().to_string();
    let mut covered: BTreeMap<String, Vec<(u32, u32, String)>> = BTreeMap::new();
    for line in json.lines().filter(|l| l.trim_start().starts_with("{\"file\"")) {
        let field = |k: &str| -> String {
            let at = line.find(&format!("\"{k}\":")).unwrap() + k.len() + 3;
            let rest = &line[at..];
            let rest = rest.strip_prefix('"').unwrap_or(rest);
            rest.split(['"', ',']).next().unwrap().to_string()
        };
        covered.entry(field("file")).or_default().push((
            field("start").parse().unwrap(),
            field("end").parse().unwrap(),
            field("role"),
        ));
    }
    let mut checked = 0;
    for f in files.iter().filter(|f| f.path != "provenance.json") {
        let spans = covered.get(&f.path).unwrap_or_else(|| panic!("{} has no span", f.path));
        if spans.iter().any(|(_, _, role)| role.starts_with("runtime shim")) {
            continue;
        }
        for n in 1..=text(f).lines().count() as u32 {
            assert!(spans.iter().any(|(s, e, _)| *s <= n && n <= *e), "{}:{n} is in no span", f.path);
            checked += 1;
        }
    }
    assert!(checked > 1000, "{checked}");
    // Guards and strategies are named where they are used.
    assert!(json.contains("\"role\":\"guard[1]\""));
    assert!(json.contains("\"strategy\":\"entry.lookup\""));
    assert!(json.contains("\"strategy\":\"entry.remove\""));
    assert!(json.contains("\"strategy\":\"filter-remove.retain\""));
    assert!(json.contains("\"strategy\":\"rule.read-only\""));
    assert!(json.contains("\"role\":\"cli param table row\""));
}

#[test]
fn runtime_shims_parse() {
    for (path, source) in spec_lang_emit_rust::rust::RUNTIME {
        if let Err(e) = syn::parse_file(source) {
            panic!("{path}: {e}");
        }
    }
}

/// The generated crate's own gate: clippy, its tests, the release build. Slow: run with `--ignored`.
#[test]
#[ignore = "builds the generated crate with cargo; run explicitly"]
fn generated_crate_passes_its_gate() {
    emits_the_todo_app();
    let status = std::process::Command::new(common::poc().join("gen/rust/bin/check")).status().unwrap();
    assert!(status.success());
}

fn emit_plain() -> Vec<OutFile> {
    let (prog, app) = common::todo("TodoRust");
    spec_lang_emit_rust::emit_with(&prog, prog.app(app), &spec_lang_emit_rust::Options::plain())
        .unwrap_or_else(|ds| panic!("{ds:?}"))
}

/// With every strategy off, nothing names one, and the plain translation still parses.
#[test]
fn every_strategy_switches_off() {
    let files = emit_plain();
    let json = files.iter().find(|f| f.path == "provenance.json").map(text).unwrap();
    for s in spec_lang_emit_rust::STRATEGIES {
        assert!(!json.contains(&format!("\"strategy\":\"{s}\"")), "{s} still applied");
    }
    for f in files.iter().filter(|f| f.path.ends_with(".rs")) {
        syn::parse_file(text(f)).unwrap_or_else(|e| panic!("{}: {e}", f.path));
    }
    assert!(!files.iter().any(|f| f.path == ".cargo/config.toml"));
}

#[test]
fn an_unknown_strategy_is_refused() {
    let (prog, app) = common::todo("TodoRust");
    let mut options = spec_lang_emit_rust::Options::all();
    options.off.insert("loop.unroll".into());
    let ds = spec_lang_emit_rust::emit_with(&prog, prog.app(app), &options).expect_err("refused");
    assert!(ds[0].message.contains("unknown strategy loop.unroll"));
}

/// The plain translation's own gate, in a directory of the build. Run with `--ignored`;
/// parity against it is run from the POC's runner with this directory's binary.
#[test]
#[ignore = "builds a second generated crate with cargo; run explicitly"]
fn plain_translation_passes_its_gate() {
    let dir = std::path::Path::new(env!("CARGO_TARGET_TMPDIR")).join("plain-rust");
    spec_lang_emit_rust::write(&dir, &emit_plain()).unwrap();
    let status = std::process::Command::new(dir.join("bin/check")).status().unwrap();
    assert!(status.success());
}

/// A strategy off by default is there when asked for, and named in provenance.
#[test]
fn an_off_by_default_strategy_can_be_asked_for() {
    let (prog, app) = common::todo("TodoRust");
    let files = spec_lang_emit_rust::emit_with(&prog, prog.app(app), &spec_lang_emit_rust::Options::all()).unwrap();
    let tag = files.iter().find(|f| f.path == "src/model/tag.rs").map(text).unwrap();
    assert!(tag.contains("bytes: [u8; 32]"), "{tag}");
    let json = files.iter().find(|f| f.path == "provenance.json").map(text).unwrap();
    assert!(json.contains("\"strategy\":\"text.inline\""));
    for f in files.iter().filter(|f| f.path.ends_with(".rs")) {
        syn::parse_file(text(f)).unwrap_or_else(|e| panic!("{}: {e}", f.path));
    }
}
