//! The todo program, end to end through the IR: the emitted Ruby project,
//! its provenance, and that every Ruby file passes `ruby -wc` and Prism.

#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]

use emit_ts::sem::prov;
use std::path::{Path, PathBuf};
use std::process::Command;

fn todo() -> spec_lang_ir::Program {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../pocs/todo-app/src");
    match spec_lang_ir::load_project(&dir) {
        Ok(p) => p,
        Err(e) => panic!("{}", e.render()),
    }
}

fn ruby_app(p: &spec_lang_ir::Program) -> &spec_lang_ir::AppDecl {
    p.apps.iter().find(|a| a.target.as_deref() == Some("ruby")).unwrap()
}

fn emitted(p: &spec_lang_ir::Program) -> Vec<prov::Tracked> {
    match emit_ruby::emit_tracked(p, ruby_app(p)) {
        Ok(files) => files,
        Err(d) => panic!("{}", d.human(&p.sources)),
    }
}

fn text_of<'a>(files: &'a [prov::Tracked], path: &str) -> &'a str {
    &files.iter().find(|f| f.path == path).unwrap_or_else(|| panic!("no {path}")).text
}

fn is_ruby(f: &prov::Tracked) -> bool {
    f.path.ends_with(".rb") || f.path.starts_with("exe/") || f.path == "Gemfile"
}

/// A fresh directory under the build's own temporary directory.
fn scratch(name: &str) -> PathBuf {
    let dir = Path::new(env!("CARGO_TARGET_TMPDIR")).join(name);
    let _ = std::fs::remove_dir_all(&dir);
    std::fs::create_dir_all(&dir).unwrap();
    dir
}

#[test]
fn the_same_input_gives_the_same_bytes() {
    let p = todo();
    let a = emit_ruby::emit(&p, ruby_app(&p)).unwrap();
    let b = emit_ruby::emit(&todo(), ruby_app(&p)).unwrap();
    assert_eq!(a, b);
}

#[test]
fn every_ruby_file_passes_ruby_wc_and_round_trips_through_prism() {
    let p = todo();
    let dir = scratch("ruby-syntax");
    let files = emit_ruby::emit(&p, ruby_app(&p)).unwrap();
    emit_ts::out::write(&dir, &files).unwrap();
    let ruby: Vec<String> = emitted(&p).iter().filter(|f| is_ruby(f)).map(|f| f.path.clone()).collect();
    assert!(ruby.len() > 40, "{} Ruby files", ruby.len());
    for path in &ruby {
        let out = Command::new("ruby").arg("-wc").arg(dir.join(path)).output().expect("ruby is on PATH");
        let report = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
        assert_eq!(report.trim(), "Syntax OK", "{path}");
    }
    let script = "require \"prism\"; bad = ARGV.reject { |f| Prism.parse_file(f).success? }; abort(bad.join(\"\\n\")) unless bad.empty?";
    let out = Command::new("ruby")
        .arg("-e")
        .arg(script)
        .args(ruby.iter().map(|f| dir.join(f)))
        .output()
        .expect("ruby is on PATH");
    assert!(out.status.success(), "Prism refused: {}", String::from_utf8_lossy(&out.stderr));
}

#[test]
fn every_generated_file_names_its_source_and_every_line_has_provenance() {
    let p = todo();
    let files = emitted(&p);
    for f in &files {
        let rows = prov::spans(f).unwrap_or_else(|e| panic!("{e}"));
        let mut next = 1;
        for r in &rows {
            assert_eq!(r.start, next, "{}: a gap before line {}", f.path, r.start);
            next = r.end + 1;
        }
        assert_eq!(next, f.text.lines().count() + 1, "{}: lines after the last span", f.path);
        if rows[0].entry.role.starts_with("runtime shim") {
            assert!(f.text.contains("Runtime shim of the ruby backend of spec-lang build"), "{}", f.path);
            continue;
        }
        for r in &rows {
            assert!(
                !r.entry.decl.is_empty() && !r.entry.strategy.is_empty() && !r.entry.fact.is_empty(),
                "{}:{}",
                f.path,
                r.start
            );
            assert!(
                r.entry.slg.contains(".slg:") && !r.entry.slg.starts_with('/'),
                "{}:{}: {}",
                f.path,
                r.start,
                r.entry.slg
            );
        }
        if is_ruby(f) || f.path.starts_with("bin/") {
            assert!(f.text.contains("Generated by spec-lang build from "), "{}", f.path);
        }
    }
}

#[test]
fn every_guard_has_its_anchor_above_it() {
    let p = todo();
    let files = emitted(&p);
    let done = text_of(&files, "lib/todo/board/done.rb");
    // The line above each guard is its anchor: the spec file and line, the declaration, the guard's number.
    let lines: Vec<&str> = done.lines().collect();
    let guards = [
        ("raise App::NoTask unless world.tasks.key?(no)", "guard[0]"),
        ("raise App::AlreadyDone unless world.tasks.fetch(no).status == :Open", "guard[1]"),
    ];
    for (guard, role) in guards {
        let at = lines.iter().position(|l| l.trim() == guard).unwrap_or_else(|| panic!("no `{guard}` in\n{done}"));
        let anchor = lines[at - 1].trim();
        assert!(
            anchor.starts_with("# slg: todo/board.slg:") && anchor.ends_with(&format!(" todo.board.done {role}")),
            "{anchor}"
        );
    }
    // A rule that assigns no state drafts nothing and hands back the world it was given.
    let stats = text_of(&files, "lib/todo/board/stats.rb");
    assert!(stats.contains("Runtime::Outcome.new(world:, lines:, reply: nil)") && !stats.contains(".dup"), "{stats}");
    let commands = text_of(&files, "lib/app/commands.rb");
    assert!(
        commands.contains("name: \"stats\",\n    access: :read")
            && commands.contains("name: \"add\",\n    access: :write"),
        "{commands}"
    );
}

#[test]
fn an_unsupported_form_is_a_diagnostic_with_a_place_and_a_fix() {
    let source = "use cli;\nstate n: Int = 0;\n@on(cli(\"bump\"))\n@uses(n.write)\npub rule bump() = { n = n / 2; }\n@target(ruby)\n@bin(\"t\")\n@store(file(\".t.json\"))\napp T(rules: [bump]);\n";
    let p = spec_lang_ir::load_sources(vec![("m".into(), "m.slg".into(), source.into())])
        .unwrap_or_else(|e| panic!("{}", e.render()));
    let d = emit_ruby::emit(&p, &p.apps[0]).unwrap_err();
    assert_eq!(d.code, "E-UNSUPPORTED");
    assert_eq!(d.decl.as_deref(), Some("m.bump"));
    assert!(d.span.is_some() && d.notes.iter().any(|n| n.starts_with("fix: ")), "{d:?}");
}
