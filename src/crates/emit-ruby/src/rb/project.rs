pub fn files(app: &App<'_>) -> Vec<Tracked> {
    let info = &app.decl.info;
    let from = format!("app {} ({})", info.name, slg(app.p, info, info.name_span));
    let config = |role: &str, strategy: &str, fact: &str| Entry {
        decl: app.p.qualified(info),
        slg: slg(app.p, info, info.span),
        role: role.into(),
        strategy: strategy.into(),
        fact: fact.into(),
    };
    let mut out = Vec::new();
    for (path, text, what) in SHIMS {
        let header = format!(
            "# frozen_string_literal: true\n\n# Runtime shim of the ruby backend of spec-lang build: {what}. The same in every generated project; change the backend, not this file.\n\n"
        );
        let entry = Entry {
            decl: String::new(),
            slg: String::new(),
            role: format!("runtime shim: {what}"),
            strategy: "runtime.verbatim: the same file in every project of this backend".into(),
            fact: "the spec does not determine it per program".into(),
        };
        out.push(Tracked {
            path: path.to_string(),
            text: format!("{header}{text}"),
            entries: vec![entry],
            executable: false,
        });
    }
    let generated = format!("# Generated by spec-lang build from {from}. {HEADER_TAIL}");
    let gemfile = format!(
        "# frozen_string_literal: true\n\n{generated}\n\n# Test only. The program itself runs with RubyGems disabled and needs no gem.\nsource \"https://rubygems.org\"\n\nruby \">= 4.0\"\n\ngem \"minitest\", \"6.0.0\"\n"
    );
    out.push(Tracked {
        path: "Gemfile".into(),
        text: gemfile,
        entries: vec![config(
            "project config: gems",
            "deps.none-at-run-time: the standard library only; minitest is pinned for the gate",
            "`@target(ruby)`",
        )],
        executable: false,
    });
    out.push(Tracked {
        path: ".gitignore".into(),
        text: "vendor/bundle/\n.bundle/\nGemfile.lock\n".into(),
        entries: vec![config("project config: ignored files", "ignore.build-output", "`@target(ruby)`")],
        executable: false,
    });
    let exe = format!(
        "#!/usr/bin/env -S ruby --disable-gems\n# frozen_string_literal: true\n\n{generated}\n\n# The program uses the standard library only, so RubyGems is never loaded (the shebang), and a run\n# requires only the files its command needs.\nrequire_relative \"../lib/app/cli\"\n\n# Die quietly, as other tools do, when the reader of our output has gone away.\nSignal.trap(\"PIPE\", \"SYSTEM_DEFAULT\")\n$stdout.binmode\n$stderr.binmode\nexit Runtime::CLI.run(App::APP, ARGV, env: ENV, out: $stdout, err: $stderr)\n"
    );
    out.push(Tracked {
        path: format!("exe/{}", app.bin),
        text: exe,
        entries: vec![config(
            "entry point",
            "startup.no-gems-lazy-requires: RubyGems is disabled and each run loads only what its command needs",
            "no gem is used at run time; parsing is derived from the rule's parameters, not from its body",
        )],
        executable: true,
    });
    let files_ok = "while IFS= read -r file; do\n  if ! report=$(ruby -wc \"$file\" 2>&1) || [ \"$report\" != \"Syntax OK\" ]; then\n    printf '%s: %s\\n' \"$file\" \"$report\" >&2\n    exit 1\n  fi\ndone";
    let script = |what: &str, body: &str| {
        format!("#!/usr/bin/env bash\n{generated}\n# {what}\nset -euo pipefail\ncd \"$(dirname \"$0\")/..\"\n\n{body}")
    };
    let build = format!(
        "chmod +x exe/{bin}\n{files_ok} < <(find exe lib -type f | sort)\necho \"built exe/{bin}\"\n",
        bin = app.bin
    );
    let check = format!(
        "bundle check >/dev/null || bundle install\n\n{files_ok} < <(find Gemfile exe lib test -type f | sort)\n\nlog=$(mktemp)\ntrap 'rm -f \"$log\"' EXIT\nbundle exec ruby -w -Ilib -Itest -e 'Dir[\"test/**/*_test.rb\"].sort.each {{ |file| require File.expand_path(file) }}' 2>&1 | tee \"$log\"\nif grep -q 'warning:' \"$log\"; then\n  echo \"the tests ran with warnings\" >&2\n  exit 1\nfi\n\nbin/build\n"
    );
    out.push(Tracked {
        path: "bin/build".into(),
        text: script("Ruby has no compile step: the build makes the executable runnable and proves every product file parses without a warning.", &build),
        entries: vec![config("build script", "build.syntax-check", "`@target(ruby)`")],
        executable: true,
    });
    out.push(Tracked {
        path: "bin/check".into(),
        text: script(
            "The whole gate: `ruby -w` on every file, the tests with warnings on, build. Any warning fails it.",
            &check,
        ),
        entries: vec![config("gate script", "gate.ruby: ruby -wc, minitest under -w, build", "`@target(ruby)`")],
        executable: true,
    });
    out
}
