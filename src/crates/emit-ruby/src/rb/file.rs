//! One generated Ruby file while it is being built: the namespace it reopens,
//! its statements, the files it requires, and the provenance of each span.

use super::ast::Stmt;
use super::print;
use emit_ts::sem::prov::{Entry, Tracked};
use std::collections::BTreeSet;

pub const HEADER_TAIL: &str = "Do not edit: change the spec and build again.";

#[derive(Debug)]
pub struct RFile {
    pub path: String,
    /// The first line of an executable.
    pub shebang: Option<String>,
    /// The modules the file's statements live in: `["Todo", "Board"]`.
    pub namespace: Vec<String>,
    /// Project files this one needs loaded, by project path.
    requires: BTreeSet<String>,
    /// Libraries: `strscan`, `minitest/autorun`.
    pub libs: BTreeSet<String>,
    pub items: Vec<Stmt>,
    pub sources: Vec<String>,
    pub entries: Vec<Entry>,
}

impl RFile {
    pub fn new(path: &str, namespace: &[&str]) -> Self {
        RFile {
            path: path.to_string(),
            shebang: None,
            namespace: namespace.iter().map(|s| s.to_string()).collect(),
            requires: BTreeSet::new(),
            libs: BTreeSet::new(),
            items: Vec::new(),
            sources: Vec::new(),
            entries: Vec::new(),
        }
    }

    /// Note that this file uses something `path` defines.
    pub fn need(&mut self, path: &str) {
        if path != self.path {
            self.requires.insert(path.to_string());
        }
    }

    /// Start a span of provenance: the comment that opens it.
    pub fn anchor(&mut self, entry: Entry) -> Stmt {
        let text = entry.anchor();
        self.entries.push(entry);
        Stmt::Comment(text)
    }

    /// How this file names another project file: relative from `lib`, by load path from `test`.
    fn require_line(&self, to: &str) -> String {
        let bare = to.trim_end_matches(".rb");
        if self.path.starts_with("test/") {
            let on_path = bare.strip_prefix("lib/").or_else(|| bare.strip_prefix("test/")).unwrap_or(bare);
            return format!("require \"{on_path}\"");
        }
        let from: Vec<&str> = self.path.split('/').collect();
        let to: Vec<&str> = bare.split('/').collect();
        let dir = &from[..from.len() - 1];
        let common = dir.iter().zip(to.iter()).take_while(|(a, b)| a == b).count();
        format!("require_relative \"{}{}\"", "../".repeat(dir.len() - common), to[common..].join("/"))
    }

    pub fn finish(self, header_entry: Entry) -> Tracked {
        let executable = self.shebang.is_some();
        let mut text = self.shebang.as_ref().map(|s| format!("{s}\n")).unwrap_or_default();
        text.push_str("# frozen_string_literal: true\n\n");
        text.push_str(&format!("# Generated by spec-lang build from {}. {HEADER_TAIL}\n\n", self.sources.join(", ")));
        for lib in &self.libs {
            text.push_str(&format!("require \"{lib}\"\n"));
        }
        for r in &self.requires {
            text.push_str(&self.require_line(r));
            text.push('\n');
        }
        if !(self.libs.is_empty() && self.requires.is_empty()) {
            text.push('\n');
        }
        let mut body = self.items.clone();
        for name in self.namespace.iter().rev() {
            body = vec![Stmt::Module { name: name.clone(), body }];
        }
        print::stmts(&body, 0, &mut text);
        let mut entries = vec![header_entry];
        entries.extend(self.entries);
        Tracked { path: self.path, text, entries, executable }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn requires_are_relative_in_lib_and_by_load_path_in_test() {
        let f = RFile::new("lib/todo/board/add.rb", &[]);
        assert_eq!(f.require_line("lib/todo/model/task.rb"), "require_relative \"../model/task\"");
        assert_eq!(f.require_line("lib/runtime/values.rb"), "require_relative \"../../runtime/values\"");
        let t = RFile::new("test/todo/laws_test.rb", &[]);
        assert_eq!(t.require_line("lib/app/world.rb"), "require \"app/world\"");
        assert_eq!(t.require_line("test/support/testing.rb"), "require \"support/testing\"");
    }
}
