//! One Ruby file per module: its types, constants, states, functions, rules and laws, in source order,
//! each under a comment that names the declaration and its line.

use crate::code;
use crate::expr::keywords_from;
use crate::gen_::{Fx, Gen, R, variant_const};
use crate::names;
use spec_lang_ir::ModuleId;
use spec_lang_lir::node::{Expr, ExprKind};
use spec_lang_lir::{Body, DTy, Extern, Field, Guard, Info, Param, TypeDecl, TypeDef};

pub(crate) const HEADER: &str = "# frozen_string_literal: true\n";

/// The comment over a declaration: what it is, where it is written, and its `@why`.
pub(crate) fn provenance(g: &Gen<'_>, kind: &str, info: &Info) -> Vec<String> {
    let mut lines = vec![format!("# {kind} {} ({})", info.name, g.at(info.span))];
    if let Some(why) = &info.why {
        lines.push(format!("# @why {}", why.replace('\n', " ")));
    }
    lines
}

/// The file of module `m`, or nothing when it declares nothing that runs.
pub(crate) fn module_file(g: &Gen<'_>, m: ModuleId) -> R<Option<String>> {
    let lir = g.lir;
    let mut decls: Vec<(u32, String)> = Vec::new();
    for (i, t) in lir.types.iter().enumerate() {
        if t.info.module == m && !t.builtin {
            decls.push((t.info.span.lo, type_decl(g, spec_lang_ir::TypeId(crate::id32(i)), t)?));
        }
    }
    for c in lir.consts.iter().filter(|c| c.info.module == m) {
        let mut fx = Fx::method(g, m);
        let name = names::method(&c.info.name);
        let value = fx.expr(&c.value)?;
        let literal = matches!(c.value.kind, ExprKind::Int(_) | ExprKind::Text(_) | ExprKind::Bool(_));
        let body = if literal && !value.multi() {
            format!("def self.{name} = {}", value.text)
        } else {
            format!(
                "def self.{name}\n  return @{name} if defined?(@{name})\n\n{}\nend",
                code::indent(&crate::stmt::assign(&format!("@{name}"), &value.text))
            )
        };
        decls.push((c.info.span.lo, with_comment(provenance(g, "const", &c.info), &body)));
    }
    for (i, s) in lir.states.iter().enumerate().filter(|(_, s)| s.info.module == m) {
        let name = names::method(&s.info.name);
        let member = &g.names.world[i];
        let body = format!(
            "def self.{name} = Spec.world.{member}\n\ndef self.{name}=(value)\n  Spec.world = Spec.world.with({member}: value)\nend"
        );
        decls.push((s.info.span.lo, with_comment(provenance(g, "state", &s.info), &body)));
    }
    for f in lir.fns.iter().filter(|f| f.info.module == m) {
        let text = callable(g, m, &f.info, &f.params, &[], &f.body, f.result_check.as_ref(), false)?;
        decls.push((f.info.span.lo, with_comment(provenance(g, "fn", &f.info), &text)));
    }
    for r in lir.rules.iter().filter(|r| r.info.module == m) {
        let text = callable(g, m, &r.info, &r.params, &r.guards, &r.body, r.result_check.as_ref(), true)?;
        decls.push((r.info.span.lo, with_comment(provenance(g, "rule", &r.info), &text)));
    }
    for l in lir.laws.iter().filter(|l| l.info.module == m) {
        let mut fx = Fx::method(g, m);
        let params: Vec<String> = l.params.iter().map(|p| fx.bind_param(&p.name)).collect();
        let body = fx.value_lines(&l.body)?;
        let text = def(&names::method(&l.info.name), &params, &body);
        decls.push((l.info.span.lo, with_comment(provenance(g, "law", &l.info), &text)));
    }
    if decls.is_empty() {
        return Ok(None);
    }
    decls.sort_by_key(|(at, _)| *at);
    let body = decls.into_iter().map(|(_, d)| d).collect::<Vec<_>>().join("\n\n");
    let module = &lir.modules[m.index()];
    let mut out = format!(
        "{HEADER}\n# Generated by spec-lang build from module {} ({}). Do not edit: change the spec and build again.\n\n",
        module.name,
        g.source(&module.path)
    );
    out.push_str(&nest(g.names.module(m), &body));
    out.push('\n');
    Ok(Some(out))
}

/// `body` inside `module A ... module B ... end end`.
pub(crate) fn nest(path: &[String], body: &str) -> String {
    let mut text = body.to_string();
    for part in path.iter().rev() {
        text = format!("module {part}\n{}\nend", code::indent(&text));
    }
    text
}

fn with_comment(mut comment: Vec<String>, body: &str) -> String {
    comment.push(body.to_string());
    comment.join("\n")
}

/// `def self.name(params)` over `body`; one line when the body is one short expression.
pub(crate) fn def(name: &str, params: &[String], body: &[String]) -> String {
    let head = code::list(&format!("def self.{name}"), "(", params, ")");
    let head = if params.is_empty() { format!("def self.{name}") } else { head };
    if let [one] = body
        && !one.contains('\n')
        && !head.contains('\n')
        && head.len() + one.len() + 3 <= code::WIDTH
        && !one.starts_with("return")
        && !one.contains(" = ")
    {
        return format!("{head} = {one}");
    }
    format!("{head}\n{}\nend", code::indent_lines(body))
}

/// The parameters as Ruby takes them, each bound in `fx`: by position up to the first default, then by keyword.
pub(crate) fn signature(fx: &mut Fx<'_>, params: &[Param]) -> R<Vec<String>> {
    let keywords = keywords_from(params);
    let mut out = Vec::new();
    for (i, p) in params.iter().enumerate() {
        let default = match &p.default {
            Some(d) => Some(fx.expr(d)?.text),
            None => None,
        };
        let name = fx.bind_param(&p.name);
        out.push(match default {
            _ if i < keywords => name,
            Some(d) => format!("{name}: {d}"),
            None => format!("{name}:"),
        });
    }
    Ok(out)
}

/// A `fn` or a rule: the prologue (every argument against its declared type), a rule's guards in order, the
/// body, the result against its type. A rule is one atomic step (`Spec.rule`).
#[allow(clippy::too_many_arguments)]
fn callable(
    g: &Gen<'_>,
    m: ModuleId,
    info: &Info,
    params: &[Param],
    guards: &[Guard],
    body: &Body,
    result: Option<&DTy>,
    rule: bool,
) -> R<String> {
    let mut fx = Fx::method(g, m);
    let sig = signature(&mut fx, params)?;
    let mut lines = Vec::new();
    for p in params {
        if fx.strict(&p.check) {
            let local = fx.lookup(&p.name);
            lines.push(fx.checked(&p.check, local, &format!("argument `{}`", p.name))?);
            fx.proved.push((p.name.clone(), p.check.clone()));
        }
    }
    for guard in guards {
        let cond = fx.scoped(|fx| fx.value_lines(&guard.cond))?;
        lines.push(code::block(&format!("Spec.guard({})", code::string(&guard.error)), &[], &cond).text);
    }
    let check = match result {
        Some(t) if fx.strict(t) => Some(fx.dty(t)?),
        _ => None,
    };
    match body {
        Body::Extern(x) => {
            let call = extern_call(&fx, info, params, x);
            lines.push(match &check {
                Some(t) => code::call(&format!("{t}.check"), &[call, code::string("the result")]).text,
                None => call,
            });
        }
        Body::Expr(Expr { kind: ExprKind::Block(b), .. }) => lines.extend(fx.body_lines(b, check, true)?),
        Body::Expr(e) => match &check {
            Some(t) => {
                let v = fx.expr(e)?.text;
                lines.push(code::call(&format!("{t}.check"), &[v, code::string("the result")]).text);
            }
            None => lines.extend(fx.value_lines(e)?),
        },
    }
    let name = names::method(&info.name);
    if rule {
        let atomic = format!("Spec.rule do\n{}\nend", code::indent_lines(&lines));
        return Ok(def(&name, &sig, &[atomic]));
    }
    Ok(def(&name, &sig, &lines))
}

/// A foreign body: the library's runtime runs it, by `library#symbol`.
fn extern_call(fx: &Fx<'_>, info: &Info, params: &[Param], x: &Extern) -> String {
    let symbol = if x.library.is_empty() { x.symbol.clone() } else { format!("{}#{}", x.library, x.symbol) };
    let mut args = vec![code::string(&symbol), code::string(&info.qualified)];
    args.extend(params.iter().map(|p| fx.lookup(&p.name)));
    code::call("Spec.extern", &args).text
}

fn type_decl(g: &Gen<'_>, id: spec_lang_ir::TypeId, t: &TypeDecl) -> R<String> {
    let m = t.info.module;
    let name = g.names.type_const(id).to_string();
    let spec_name = code::string(&t.info.name);
    let body = match &t.def {
        TypeDef::Alias { of } => {
            let mut fx = Fx::method(g, m);
            let of = fx.dty(of)?;
            code::block(&format!("{name} = Spec::Type.alias({spec_name})"), &[], &[of]).text
        }
        TypeDef::RuleSet { rules } => {
            let mut args = vec![spec_name];
            args.extend(rules.iter().map(|r| code::string(&g.lir.rule(*r).info.qualified)));
            format!("{name} = {}", code::call("Spec::Type.rules", &args).text)
        }
        TypeDef::Record { fields } => record(g, m, &name, &spec_name, fields)?,
        TypeDef::Sum { variants } => {
            let mut fx = Fx::inside(g, m);
            fx.rooted = true;
            let mut lines = vec!["extend Spec::Sum".to_string(), String::new(), format!("spec {spec_name}")];
            for v in variants {
                let mut args = vec![code::string(&v.name)];
                args.extend(v.fields.iter().map(|f| format!(":{}", names::member(&f.name))));
                if v.fields.iter().any(|f| names::member(&f.name) != f.name) {
                    let written: Vec<String> = v.fields.iter().map(|f| f.name.clone()).collect();
                    args.push(format!("field_names: {}", code::words(&written)));
                }
                let head = code::call(&format!("{} = variant", variant_const(&v.name)), &args).text;
                lines.push(if v.fields.is_empty() {
                    head
                } else {
                    let types = field_types(&mut fx, &v.fields)?;
                    code::block(&head, &[], &[types]).text
                });
            }
            format!("module {name}\n{}\nend", code::indent_lines(&lines))
        }
    };
    let kind = "type";
    Ok(with_comment(provenance(g, kind, &t.info), &body))
}

fn field_types(fx: &mut Fx<'_>, fields: &[Field]) -> R<String> {
    let types = fields.iter().map(|f| fx.dty(&f.check)).collect::<R<Vec<_>>>()?;
    Ok(code::list("", "[", &types, "]"))
}

/// A record: a `Data` whose `initialize` gives the defaults and checks every field that has a claim.
fn record(g: &Gen<'_>, m: ModuleId, name: &str, spec_name: &str, fields: &[Field]) -> R<String> {
    let mut fx = Fx::inside(g, m);
    let members: Vec<String> = fields.iter().map(|f| names::member(&f.name)).collect();
    let head =
        code::call(&format!("{name} = Data.define"), &members.iter().map(|m| format!(":{m}")).collect::<Vec<_>>());
    let head = if members.is_empty() { format!("{name} = Data.define") } else { head.text };
    let renamed = fields.iter().zip(&members).any(|(f, m)| f.name != *m);
    let written: Vec<String> = fields.iter().map(|f| f.name.clone()).collect();
    let spec_head =
        if renamed { format!("spec({spec_name}, {})", code::words(&written)) } else { format!("spec({spec_name})") };
    let mut lines = vec![
        "extend Spec::Record".to_string(),
        String::new(),
        code::block(&spec_head, &[], &[field_types(&mut fx, fields)?]).text,
    ];
    let strict = fields.iter().any(|f| fx.strict(&f.check));
    if strict || fields.iter().any(|f| f.default.is_some()) {
        let mut params = Vec::new();
        for (f, member) in fields.iter().zip(&members) {
            params.push(match &f.default {
                Some(d) => format!("{member}: {}", fx.expr(d)?.text),
                None => format!("{member}:"),
            });
        }
        let mut body = vec!["super".to_string()];
        if strict {
            body.push("self.class.claim!(self)".into());
        }
        lines.push(String::new());
        lines.push(format!("{}\n{}\nend", code::list("def initialize", "(", &params, ")"), code::indent_lines(&body)));
    }
    Ok(format!("{head} do\n{}\nend", code::indent_lines(&lines)))
}
