//! `test/checks/`: the program's own tests, cases, properties and laws, one file per module, registered
//! under the names `spec-lang test` gives them.

use crate::code;
use crate::decls::{HEADER, def, provenance, signature};
use crate::gen_::{Fx, Gen, R, snake};
use crate::names;
use spec_lang_ir::ModuleId;
use spec_lang_lir::node::Expected;
use spec_lang_lir::{CaseTarget, Check, CheckWhat, Given, Test};

/// `TodoBoardChecks`, the module that holds the checks of `todo.board`.
fn checks_const(g: &Gen<'_>, m: ModuleId) -> String {
    format!("{}Checks", g.names.module(m).join(""))
}

/// `todo/board`: the file of a module's checks, under `test/checks/`.
pub(crate) fn file_name(g: &Gen<'_>, m: ModuleId) -> String {
    g.names.module(m).iter().map(|s| snake(s)).collect::<Vec<_>>().join("/")
}

fn fx<'a>(g: &'a Gen<'a>) -> Fx<'a> {
    let mut fx = Fx::outside(g);
    // Inside `module Checks`, a module of the program named like one of the checks' modules would hide.
    let taken: Vec<String> = (0..g.lir.modules.len()).map(|i| checks_const(g, ModuleId(crate::id32(i)))).collect();
    fx.rooted = (0..g.lir.modules.len())
        .any(|i| g.names.module(ModuleId(crate::id32(i))).first().is_some_and(|first| taken.contains(first)));
    fx
}

/// The checks file of module `m`, or nothing when it has no test and no check.
pub(crate) fn module_file(g: &Gen<'_>, m: ModuleId) -> R<Option<String>> {
    let lir = g.lir;
    let module = &lir.modules[m.index()];
    let mut parts = Vec::new();
    for t in lir.tests.iter().filter(|t| t.info.module == m) {
        parts.push(test(g, t)?);
    }
    let mut checks = Vec::new();
    for c in lir.checks.iter().filter(|c| c.module == module.name) {
        checks.push(check(g, c)?);
    }
    if parts.is_empty() && checks.is_empty() {
        return Ok(None);
    }
    if !checks.is_empty() {
        parts.push(checks.join("\n"));
    }
    let body = format!("SUITE = Spec::Testing.suite\n\n{}", parts.join("\n\n"));
    let nested = crate::decls::nest(&["Checks".to_string(), checks_const(g, m)], &body);
    Ok(Some(format!(
        "{HEADER}\n# Generated by spec-lang build from the tests of module {} ({}). Do not edit: change the spec and build again.\n\n{nested}\n",
        module.name,
        g.source(&module.path)
    )))
}

/// A test: a method that runs its steps, registered with its `@given` items.
fn test(g: &Gen<'_>, t: &Test) -> R<String> {
    let mut f = fx(g);
    let name = names::method(&t.info.name);
    let sig = signature(&mut f, &t.params)?;
    let body = f.body_lines(&t.body, None, false)?;
    let method =
        if body.is_empty() { format!("def self.{name}{}; end", parens(&sig)) } else { def(&name, &sig, &body) };
    let mut args = vec![code::string(&t.info.qualified), format!("method(:{name})")];
    if !t.params.is_empty() {
        let mut params = Vec::new();
        for p in &t.params {
            let ty = f.dty(&p.check)?;
            params.push(format!("Spec::Param.new({}, -> {{ {ty} }})", code::string(&p.name)));
        }
        args.push(format!("params: {}", code::list("", "[", &params, "]")));
    }
    if !t.given.is_empty() {
        let mut given = Vec::new();
        for item in &t.given {
            given.push(match item {
                Given::Test(parent) => format!("SUITE.after({})", code::string(&g.lir.test(*parent).info.qualified)),
                Given::State { state, value } => {
                    let head = format!("SUITE.set({})", code::string(&g.lir.state(*state).info.qualified));
                    let value = f.scoped(|f| f.value_lines(value))?;
                    code::block(&head, &[], &value).text
                }
            });
        }
        args.push(format!("given: {}", code::list("", "[", &given, "]")));
    }
    let mut lines = provenance(g, "test", &t.info);
    lines.push(method);
    lines.push(code::call("SUITE.test", &args).text);
    Ok(lines.join("\n"))
}

fn parens(sig: &[String]) -> String {
    if sig.is_empty() { String::new() } else { format!("({})", sig.join(", ")) }
}

fn check(g: &Gen<'_>, c: &Check) -> R<String> {
    let lir = g.lir;
    let name = code::string(&c.name);
    Ok(match &c.what {
        CheckWhat::Test(_) => format!("SUITE.scenario({name})"),
        CheckWhat::Property(_) => format!("SUITE.property({name})"),
        CheckWhat::Law(_) => format!("SUITE.law({name})"),
        CheckWhat::Case { target: CaseTarget::Test(t), args, .. } => {
            let mut f = fx(g);
            let mut values = Vec::new();
            for a in args.iter().flatten() {
                values.push(f.expr(a)?.text);
            }
            let values = code::list("", "[", &values, "]");
            code::call(
                "SUITE.case_of",
                &[name, code::string(&lir.test(*t).info.qualified), format!("-> {{ {values} }}")],
            )
            .text
        }
        CheckWhat::Case { target: CaseTarget::Fn(func), args, expect } => {
            let mut f = fx(g);
            let d = lir.func(*func);
            let dummy = spec_lang_lir::node::Expr::new(
                spec_lang_lir::node::ExprKind::Unit,
                spec_lang_lir::LTy::Unit,
                d.info.span,
            );
            let call_args = f.args(&dummy, &d.params, args)?;
            let call = f.call_named(d.info.module, &d.info.name, &call_args).text;
            let expected = match expect {
                Expected::Value(v) => format!("gives: {}", thunk(&f.expr(v)?.text)),
                Expected::Fail { name, .. } => format!("fails: {}", code::string(name)),
            };
            code::call("SUITE.case", &[name, thunk(&call), expected]).text
        }
    })
}

fn thunk(body: &str) -> String {
    if body.contains('\n') { format!("lambda do\n{}\nend", code::indent(body)) } else { format!("-> {{ {body} }}") }
}
