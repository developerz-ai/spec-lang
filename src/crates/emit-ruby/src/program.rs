//! `lib/program.rb`: the program as data a runtime reads. Every state, rule, `fn`, law, handler and app by
//! name, with its parameters' declared types; nothing here is specific to a library.

use crate::code;
use crate::decls::HEADER;
use crate::expr::keywords_from;
use crate::gen_::{Fx, Gen, R};
use crate::names;
use spec_lang_lir::manifest::{Named, Note, NoteArg, NoteValue};
use spec_lang_lir::{Handler, Info, Manifest, OpKind, Param};

pub(crate) fn file(g: &Gen<'_>, requires: &[String]) -> R<String> {
    let lir = g.lir;
    let mut fx = Fx::outside(g);
    let mut entries = Vec::new();
    for (i, s) in lir.states.iter().enumerate() {
        let ty = fx.dty(&s.check)?;
        let init = match (&s.init, Fx::empty_of(&s.ty)) {
            (Some(e), _) => fx.expr(e)?.text,
            (None, Some(empty)) => empty.to_string(),
            (None, None) => {
                return Err(g.unsupported(
                    s.info.span,
                    "a state that is not a collection or an Option, without an initial value",
                ));
            }
        };
        let args = vec![code::string(&s.info.qualified), format!(":{}", g.names.world[i]), thunk(&ty), thunk(&init)];
        entries.push(code::call("p.state", &args).text);
    }
    for r in &lir.rules {
        let mut args = callable(&mut fx, &r.info, &r.params)?;
        if !r.triggers.is_empty() {
            let notes: Vec<String> = r.triggers.iter().map(note).collect();
            args.push(format!("triggers: {}", code::list("", "[", &notes, "]")));
        }
        args.extend(meta(&r.info, &r.uses));
        args.extend(foreign(&r.body));
        entries.push(code::call("p.rule", &args).text);
    }
    for f in &lir.fns {
        let mut args = callable(&mut fx, &f.info, &f.params)?;
        if let Some(t) = &f.result_check {
            args.push(format!("result: {}", thunk(&fx.dty(t)?)));
        }
        args.extend(meta(&f.info, &f.uses));
        args.extend(foreign(&f.body));
        entries.push(code::call("p.fn", &args).text);
    }
    for l in &lir.laws {
        let params = params(&mut fx, &l.params)?;
        let locals: Vec<String> = l.params.iter().map(|p| names::local(&p.name)).collect();
        let call = fx.call_named(l.info.module, &l.info.name, &locals).text;
        let names_of = |ids: &[spec_lang_ir::RuleId]| {
            code::words(&ids.iter().map(|r| lir.rule(*r).info.qualified.clone()).collect::<Vec<_>>())
        };
        let args = vec![
            code::string(&l.info.qualified),
            params,
            format!("->({}) {{ {call} }}", locals.join(", ")),
            format!("trace: {}", l.trace),
            format!("traced: {}", names_of(&l.traced)),
            format!("start: {}", names_of(&l.start_rules)),
        ];
        entries.push(code::call("p.law", &args).text);
    }
    for h in &lir.handlers {
        entries.push(handler(g, h)?);
    }
    for a in &lir.apps {
        entries.push(app(g, a));
    }
    let mut out = format!(
        "{HEADER}\n# Generated by spec-lang build: the program as data. Do not edit: change the spec and build again.\n\nrequire_relative \"spec\"\n"
    );
    for r in requires {
        out.push_str(&format!("require_relative {}\n", code::string(r)));
    }
    out.push_str("\n# Every state, rule, fn, law, handler and app of the program, by name.\n");
    out.push_str(&format!("PROGRAM = Spec::Program.new do |p|\n{}\nend\n", code::indent_lines(&entries)));
    Ok(out)
}

/// `extern: "raylib#DrawCube"` for a foreign body.
fn foreign(body: &spec_lang_lir::Body) -> Option<String> {
    match body {
        spec_lang_lir::Body::Extern(x) if x.library.is_empty() => Some(format!("extern: {}", code::string(&x.symbol))),
        spec_lang_lir::Body::Extern(x) => {
            Some(format!("extern: {}", code::string(&format!("{}#{}", x.library, x.symbol))))
        }
        spec_lang_lir::Body::Expr(_) => None,
    }
}

fn thunk(body: &str) -> String {
    if body.contains('\n') { format!("lambda do\n{}\nend", code::indent(body)) } else { format!("-> {{ {body} }}") }
}

fn meta(info: &Info, uses: &[String]) -> Vec<String> {
    let mut out = Vec::new();
    if let Some(why) = &info.why {
        out.push(format!("why: {}", code::string(why)));
    }
    if !uses.is_empty() {
        out.push(format!("uses: {}", code::words(uses)));
    }
    out
}

/// `[p.param("title", -> { Title }), p.param("tags", -> { ... }, optional: true)]`.
fn params(fx: &mut Fx<'_>, params: &[Param]) -> R<String> {
    let mut out = Vec::new();
    for p in params {
        let mut args = vec![code::string(&p.name), thunk(&fx.dty(&p.check)?)];
        if p.default.is_some() {
            args.push("optional: true".into());
        }
        out.push(code::call("p.param", &args).text);
    }
    Ok(code::list("", "[", &out, "]"))
}

/// Name, parameters, and a lambda that calls the declaration with every argument in one Array; an argument
/// that is `Spec::ABSENT` takes the declaration's default.
fn callable(fx: &mut Fx<'_>, info: &Info, ps: &[Param]) -> R<Vec<String>> {
    let keywords = keywords_from(ps);
    let positional: Vec<String> = (0..keywords.min(ps.len())).map(|i| format!("a[{i}]")).collect();
    let named: Vec<String> =
        ps.iter().enumerate().skip(keywords).map(|(i, p)| format!("{}: a[{i}]", names::local(&p.name))).collect();
    let mut args = positional;
    if !named.is_empty() {
        args.push(format!("**Spec.given({})", named.join(", ")));
    }
    let call = fx.call_named(info.module, &info.name, &args).text;
    let a = if ps.is_empty() { "_a" } else { "a" };
    Ok(vec![code::string(&info.qualified), params(fx, ps)?, format!("->({a}) {{ {call} }}")])
}

fn note(n: &Note) -> String {
    let mut args = vec![code::string(&n.library), code::string(&n.name)];
    args.extend(n.args.iter().map(note_arg));
    code::call("p.note", &args).text
}

fn note_arg(a: &NoteArg) -> String {
    format!("{}: {}", names::local(&a.param), note_value(&a.value))
}

fn note_value(v: &NoteValue) -> String {
    match v {
        NoteValue::Int(n) => n.to_string(),
        NoteValue::Text(t) => code::string(t),
        NoteValue::Quantity { value, unit } => format!("Spec::Quantity.new({value}, {})", code::string(unit)),
        NoteValue::Variant { name, args } => {
            let pairs: Vec<String> =
                args.iter().map(|a| format!("{} => {}", code::string(&a.param), note_value(&a.value))).collect();
            format!("Spec::Choice.new({}, {{ {} }})", code::string(name), pairs.join(", "))
        }
    }
}

/// A handler: its operations, and for each the pretend arm tests run. An arm takes the pretend's state, then
/// the operation's arguments, and gives the reply and the state as it ends.
fn handler(g: &Gen<'_>, h: &Handler) -> R<String> {
    let mut args = vec![code::string(&format!("{}.{}", h.library, h.name))];
    let pretend = h.pretend.as_ref();
    if let Some(p) = pretend.filter(|p| !p.state.is_empty()) {
        let mut state = Vec::new();
        for s in &p.state {
            let mut fx = Fx::outside(g);
            let init = match (&s.default, Fx::empty_of(&s.ty)) {
                (Some(e), _) => fx.expr(e)?.text,
                (None, Some(empty)) => empty.to_string(),
                (None, None) => "nil".into(),
            };
            state.push(format!("[{}, {}]", code::string(&s.name), thunk(&init)));
        }
        args.push(format!("state: {}", code::list("", "[", &state, "]")));
    }
    let mut ops = Vec::new();
    for (i, op) in h.ops.iter().enumerate() {
        let mut fx = Fx::outside(g);
        let kind = match op.kind {
            OpKind::Rule => ":rule",
            OpKind::Fn => ":fn",
            OpKind::Test => ":test",
        };
        let mut op_args = vec![kind.to_string()];
        if let Some(ps) = &op.params {
            op_args.push(params(&mut fx, ps)?);
        }
        let head = code::call("p.operation", &op_args).text;
        let arm = pretend.and_then(|p| p.arms.get(i).and_then(|a| a.as_ref().map(|a| (p, a))));
        let text = match arm {
            None => head,
            Some((p, arm)) => {
                let mut locals: Vec<String> = p.state.iter().map(|s| fx.bind(&s.name, true)).collect();
                let state = locals.clone();
                locals.extend(arm.params.iter().map(|(n, _)| fx.bind_param(n)));
                let reply = fx.fresh("reply");
                let value = fx.expr(&arm.body)?.text;
                let body = vec![crate::stmt::assign(&reply, &value), format!("[{reply}, [{}]]", state.join(", "))];
                code::block(&head, &locals, &body).text
            }
        };
        ops.push(format!("{}: {text}", names::method(&op.name)));
    }
    if !ops.is_empty() {
        args.push(format!("ops: {}", code::list("", "{", &ops, "}")));
    }
    Ok(code::call("p.handler", &args).text)
}

/// One app's manifest.
fn app(g: &Gen<'_>, a: &Manifest) -> String {
    let lir = g.lir;
    let decl = |n: &Named| match n {
        Named::Rule(r) => lir.rule(*r).info.qualified.clone(),
        Named::Fn(f) => lir.func(*f).info.qualified.clone(),
    };
    let params: Vec<String> = a
        .params
        .iter()
        .map(|p| format!("{} => {}", code::string(&p.name), code::words(&p.decls.iter().map(decl).collect::<Vec<_>>())))
        .collect();
    let opt = |v: &Option<String>| v.as_ref().map_or("nil".to_string(), |s| code::string(s));
    let args = vec![
        code::string(&a.name),
        format!("qualified: {}", code::string(&a.qualified)),
        format!("target: {}", opt(&a.target)),
        format!("shape: {}", opt(&a.shape)),
        format!("notes: {}", code::list("", "[", &a.notes.iter().map(note).collect::<Vec<_>>(), "]")),
        format!("params: {}", code::list("", "{", &params, "}")),
        format!(
            "rules: {}",
            code::words(&a.rules.iter().map(|r| lir.rule(*r).info.qualified.clone()).collect::<Vec<_>>())
        ),
    ];
    code::call("p.app", &args).text
}
